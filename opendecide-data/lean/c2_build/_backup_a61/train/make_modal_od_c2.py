"""make_modal_od_c2.py: writes modal_od_c2.py, the C2 copy of lean/modal_od.py (which is pinned and never edited).

Why a copy (A37 i, A42-D 9.1). Checkpoint saving needs NO change: train_decoder.train() already keeps adapter
snapshots (cfg snap_fracs -> out_dir/snaps/s<step>/, committed to the Volume by on_ckpt) and the final adapter, so the
6-10 checkpoints of A42-D 9.1 are config keys in runs/q35_4b_c2.json. Three things DO need a change:
  1. DATA MOUNT. modal_od's image uploads only PARTS_KEEP files of c_parts / v14_parts; data/c2_parts/ (the C2 mix) is not
     uploaded and _launch_checks would refuse the config. The copy adds C2_KEEP = c2_train.jsonl + c2_rel.jsonl.
  2. SEALED / EVAL PATHS. _data_ignore() also drops any path part matching ohs|sealed|quarantine|longbench|jevbench|
     decision_index|ejs|jev (case-insensitive), at any depth, so no sealed or eval file can reach the training image
     (A42-D 13.1: every training glob excludes ohs3*, ohs3_parts/, ohs4_sealed/, ohs_ac_sealed/).
  3. RELAY GUARD. relay() refuses unless MODAL_PROFILE is exported and is mahadikarya2 or mahadikarya3 (A42-D 2.4: free
     credit only; the card is never used without a named owner GO) and the config is q35_4b_c2.
  HERE becomes lean/ (the copy lives in c2_build/train/), so config paths, data/, logs/relay_<name>_*.json are unchanged.

  cd lean && ../.venv/bin/python -B c2_build/train/make_modal_od_c2.py [--check]
--check: exit 1 if modal_od_c2.py is missing or was generated from another modal_od.py (preflight runs it).
"""
from __future__ import annotations

import difflib
import hashlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEAN = HERE.parents[1]
SRC, DST, DIFF = LEAN / "modal_od.py", HERE / "modal_od_c2.py", HERE / "MODAL_OD_C2.diff"
ALLOWED_PROFILES = ("mahadikarya2", "mahadikarya3")

EDITS = [
    ("HERE = Path(__file__).resolve().parent\n",
     "import os\nimport sys\n\nHERE = Path(__file__).resolve().parents[2]  # lean/ (this copy lives in c2_build/train/)\n"
     "sys.path.insert(0, str(HERE))\n"),
    ('PARTS_KEEP = {"v14_parts": V14_KEEP, "c_parts": C_KEEP}',
     'C2_KEEP = {"c2_train.jsonl", "c2_rel.jsonl"}  # C2 copy: the mixer\'s two final files only (A37 d)\n'
     'PARTS_KEEP = {"v14_parts": V14_KEEP, "c_parts": C_KEEP, "c2_parts": C2_KEEP}'),
    ('    parts = p.parts\n    if not parts:\n        return False\n',
     '    parts = p.parts\n    if not parts:\n        return False\n'
     '    if any(_C2_DENY.search(x) for x in parts):  # C2 copy: no sealed / eval path ever reaches the training image\n'
     '        return True\n'),
    ("def _data_ignore(p: Path) -> bool:",
     'import re as _re\n\n_C2_DENY = _re.compile(r"ohs|sealed|quarantine|longbench|jevbench|decision_index|ejs|jev", _re.I)\n'
     f'C2_ALLOWED_PROFILES = {ALLOWED_PROFILES!r}\n\n\ndef _data_ignore(p: Path) -> bool:'),
    ('logs more steps."""\n    cfg = json.loads((HERE / config).read_text())\n',
     'logs more steps."""\n    prof = os.environ.get("MODAL_PROFILE", "")\n'
     '    if prof not in C2_ALLOWED_PROFILES:\n'
     '        raise SystemExit(f"C2 relay: MODAL_PROFILE must be exported and one of {C2_ALLOWED_PROFILES} (free credit, '
     'A42-D 2.4), not {prof!r}")\n'
     '    cfg = json.loads((HERE / config).read_text())\n'
     '    if cfg.get("name") != "q35_4b_c2":\n'
     '        raise SystemExit(f"C2 relay: {config} is not the C2 run (name {cfg.get(\'name\')!r})")\n'),
]


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def build() -> str:
    text = SRC.read_text()
    for old, new in EDITS:
        if text.count(old) != 1:
            raise SystemExit(f"anchor not found exactly once in modal_od.py ({text.count(old)}x): {old[:60]!r}")
        text = text.replace(old, new)
    head = (f"# GENERATED by c2_build/train/make_modal_od_c2.py from lean/modal_od.py (sha256 {sha(SRC)}). Do not edit.\n"
            f"SOURCE_MODAL_OD_SHA256 = \"{sha(SRC)}\"\n")
    # the module docstring stays first and `from __future__` must precede any statement: header goes after the import
    k = "from __future__ import annotations\n"
    i = text.index(k) + len(k)
    return text[:i] + head + text[i:]


def main(argv=None) -> int:
    a = argv if argv is not None else sys.argv[1:]
    if "--check" in a:
        ok = DST.exists() and f'SOURCE_MODAL_OD_SHA256 = "{sha(SRC)}"' in DST.read_text() and DST.read_text() == build()
        print("OK: modal_od_c2.py matches the current modal_od.py" if ok else "STALE or missing modal_od_c2.py")
        return 0 if ok else 1
    new = build()
    DST.write_text(new)
    DIFF.write_text("".join(difflib.unified_diff(SRC.read_text().splitlines(True), new.splitlines(True),
                                                 "lean/modal_od.py", "c2_build/train/modal_od_c2.py")))
    print(f"wrote {DST.name} ({len(new.splitlines())} lines) and {DIFF.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
