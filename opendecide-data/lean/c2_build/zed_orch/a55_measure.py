"""A55 (e), "Measure": re-run the g13_attr c2_mixdev attribution on the REBUILT mixdevs and size the top-up. ANALYSIS ONLY: it is
not a G13 run and writes no G13 log. It re-uses g13_attr's own loaders / scan (g13_attr/attr_core.py, read-only): the engine's
c2_mixdev scan of each block's candidates (decontam_g13.TrainIndex / Scan) and the wrapper's A53 waiver (g13_c2.a53_apply).

Dev set. The batch-4 dev files (sha256-pinned in the batch-4 logs) with the files of the REBUILT families replaced by their
current files (or by `--dev FAM=PATH`, e.g. an analysis copy written by a55_rebuild_mixdev.py --out-dir). Families not named stay
exactly as batch 4 saw them (T33's superseded version included), so a difference is the rebuilt mixdevs only.

What is exact and what is an estimate
  exact      the c2_mixdev binding units under the new dev set (M_new) and their rows: the scan is the engine's.
  inherited  from the batch-4 logs and g13_attr_units.jsonl (unchanged by a dev change): the units the OTHER targets dropped
             (R = dropped units that are neither a batch-4 c2_mixdev binding unit nor an ohs4_hash hit) and the ohs4_hash hits (H4).
  estimate   a batch-4 binding unit that is not binding any more ("freed") may still be hit by another target; it is dropped with the
             probability p = rows(R) / rows(units outside M_old and H4), the same rate g13_attr uses.
  E = N - rows(R u M_new u H4) - p * rows(freed)            (point estimate; low = every freed unit is also hit, high = none)
  With the batch-4 dev (no rebuilt family) E equals the log's rows left exactly: asserted (`self_check`).

Top-up size (ruling (e) "Size"): only if E < 1.03 x target:  X = ceil((1.06 x target - E) / (s x q)),  s = E / N (G13 survival of
the candidate rows), q = the full-generation QC keep rate = candidate rows kept after G5-H / G3-H / G-SL / G12 over rows generated
(rows written by the build + the rows the units dropped by G-SL would have held, at the build's mean rows per unit). T25 has no L2.

Run from lean/:
  ../.venv/bin/python -B c2_build/zed_orch/a55_measure.py [--blocks T24 T25 ...] [--rebuilt T23 T26 T28 T12] [--dev T24=PATH ...]
        [--out PATH] [--decide]       (--decide also writes the dated decision record; it must exist before any top-up row does)
"""
from __future__ import annotations

import argparse
import json
import math
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE / "g13_attr"))
sys.path.insert(0, str(HERE.parent))
sys.dont_write_bytecode = True

import a55_common as C  # noqa: E402
import attr_core as A  # noqa: E402  (g13_attr: read-only loaders and the engine scan)

OUT_DEFAULT = HERE / "g13_attr" / "a55_measure.json"
DECISION = HERE / "g13_attr" / "A55_TOPUP_DECISION.json"
UNITS = HERE / "g13_attr" / "g13_attr_units.jsonl"


def batch4_units() -> dict:
    """{block: {"M_old": set, "H4": set}} from g13_attr_units.jsonl (one record per unit hit by a binding c2_mixdev item or an
    ohs4_hash method in batch 4)."""
    out: dict = {}
    for ln in UNITS.read_text(encoding="utf-8").splitlines():
        if not ln.strip():
            continue
        r = json.loads(ln)
        d = out.setdefault(r["block"], {"M_old": set(), "H4": set()})
        if r.get("c2_mixdev_binding"):
            d["M_old"].add(r["unit"])
        if r.get("ohs4_hash_hit"):
            d["H4"].add(r["unit"])
    return out


def batch4_dev_files_tolerant(ref_block: str = "T25") -> tuple:
    """A.batch4_dev_files, except that a batch-4 dev file that no longer exists anywhere (T32's mixdev, regenerated by another
    agent after the batch-4 run, no copy kept) is replaced by the CURRENT file of that family and says so."""
    ias = A.log_of(ref_block)["inputs_at_start"]
    pths = A.log_of(ref_block)["inputs_at_start_paths"]
    out, rec = {}, {}
    for key, sha in sorted(ias.items()):
        rel = pths.get(key) or key
        if not rel.endswith("mixdev_S5.jsonl"):
            continue
        fam = rel.split("/")[2]
        cur = A.LEAN / rel
        if A.X.resolved_refusal(cur):
            raise SystemExit(f"refused: {rel}")
        if cur.is_file() and A.sha_file(cur) == sha:
            out[fam], rec[fam] = cur, {"source": rel, "sha256": sha, "status": "current file == batch-4 file"}
            continue
        found = None
        import os
        for dp, dn, fn in os.walk(A.LEAN / "data" / "c2_parts" / fam):
            dn[:] = [d for d in dn if not A.X.resolved_refusal(Path(dp) / d)]
            for f in fn:
                if f.endswith("mixdev_S5.jsonl") and A.sha_file(Path(dp) / f) == sha:
                    found = Path(dp) / f
                    break
            if found:
                break
        if found:
            out[fam] = found
            rec[fam] = {"source": str(found.relative_to(A.LEAN)), "sha256": sha, "status": "SUPERSEDED version found by sha256"}
        elif cur.is_file():
            out[fam] = cur
            rec[fam] = {"source": rel, "sha256": A.sha_file(cur), "batch4_sha256": sha,
                        "status": "CURRENT file: the batch-4 version no longer exists (owner regenerated it)"}
        else:
            raise SystemExit(f"batch-4 dev file for {fam} (sha {sha[:12]}) not found and no current file")
    return out, rec


def dev_files(rebuilt=(), overrides: dict | None = None) -> tuple:
    files, rec = batch4_dev_files_tolerant()
    for fam in rebuilt:
        files[fam] = A.LEAN / "data" / "c2_parts" / fam / "out" / "mixdev_S5.jsonl"
        rec[fam] = {"source": f"data/c2_parts/{fam}/out/mixdev_S5.jsonl", "sha256": A.sha_file(files[fam]), "status": "CURRENT (rebuilt)"}
    for fam, p in (overrides or {}).items():
        files[fam] = Path(p)
        rec[fam] = {"source": str(p), "sha256": A.sha_file(p), "status": "OVERRIDE (analysis copy)"}
    return files, rec


def qc_keep_rate(fam: str) -> dict:
    """q: candidate rows kept after the QC drops over the rows generated (see the module docstring)."""
    d = A.LEAN / "data" / "c2_parts" / fam
    gen = json.loads((d / "qc" / "GEN_REPORT.json").read_text())
    drops = json.loads((d / "qc" / "DROPS.json").read_text())
    b = gen["build"]
    per_unit = b["rows_written"] / max(1, b["units_written"])
    gsl_rows = b.get("units_dropped", 0) * per_unit
    generated = b["rows_written"] + gsl_rows
    kept = drops["rows_after"]
    g12 = (gen.get("gates", {}).get("G12") or {}).get("exact_duplicates_dropped", 0)
    return {"rows_written_by_build": b["rows_written"], "units_dropped_in_build": b.get("units_dropped", 0),
            "est_rows_of_dropped_units": round(gsl_rows, 1), "rows_generated": round(generated, 1), "g12_exact_dropped": g12,
            "qc_dropped_rows": drops.get("dropped_rows"), "rows_after_all_drops": kept, "q": round(kept / generated, 4)}


def measure_block(B: str, dev: dict, st, b4: dict) -> dict:
    t0 = time.time()
    rows = A.load_block(B)
    sc = A.scan_block(B, rows, dev)
    units, uh = sc["units"], sc["hits"]
    umap = {u["key"]: u for u in units}
    rows_of = {k: len(u["rows"]) for k, u in umap.items()}
    allu = set(umap)
    bind, _rec = A.apply_a53(B, units, uh, st)
    M_new = {k for d in bind.values() for k in d}
    log = A.log_of(B)
    drop_ids = set(log["drop_ids"])
    D = {k for k, u in umap.items() if u["rows"] and all(r in drop_ids for r in u["rows"])}
    M_old, H4 = b4.get(B, {}).get("M_old", set()), b4.get(B, {}).get("H4", set())
    R = D - (M_old | H4)
    outside = allu - (M_old | H4)
    rr = lambda s: sum(rows_of[k] for k in s)  # noqa: E731
    p_rows = rr(R) / max(1, rr(outside))
    sure = R | M_new | H4
    freed = M_old - sure
    N = len(rows)
    left_now = N - len(drop_ids)
    E = N - rr(sure) - p_rows * rr(freed)
    low = N - rr(sure) - rr(freed)
    high = N - rr(sure)
    # the same formula on the batch-4 sets must give the log's number exactly
    self_check = N - rr(R | M_old | H4)
    return {"rows": N, "units": len(units), "target": A.c2io.ALL_TARGETS.get(B), "rows_left_batch4_log": left_now,
            "self_check_rows_left_from_sets": self_check, "self_check_ok": self_check == left_now,
            "binding_units_batch4": len(M_old), "binding_units_now": len(M_new), "binding_rows_now": rr(M_new),
            "binding_units_now_not_in_batch4": len(M_new - M_old), "freed_units": len(freed), "freed_rows": rr(freed),
            "R_units": len(R), "R_rows": rr(R), "H4_units": len(H4), "p_other_target_rows": round(p_rows, 4),
            "E": round(E), "E_low": round(low), "E_high": round(high), "shortfall_at_E": max(0, (A.c2io.ALL_TARGETS.get(B) or 0) - round(E)),
            "binding_units_by_method_now": {m: len(d) for m, d in sorted(bind.items())}, "wall_s": round(time.time() - t0, 1)}


def topup_decision(fam: str, m: dict) -> dict:
    """Ruling (e): a top-up only if E < 1.03 x target; X = ceil((1.06 x target - E) / (s x q))."""
    T = m["target"]
    E = m["E"]
    q = qc_keep_rate(fam)
    s = E / m["rows"]
    trigger = C.TOPUP_MARGIN_TRIGGER * T
    out = {"family": fam, "target": T, "E": E, "E_low": m["E_low"], "E_high": m["E_high"], "candidate_rows": m["rows"],
           "s": round(s, 4), "q": q["q"], "qc_keep_rate_detail": q, "trigger_E_below": round(trigger, 1),
           "topup_allowed": fam not in C.NO_L2}
    if fam in C.NO_L2:
        out.update({"topup": False, "why": "T25: a plain top-up has no abstain class (ruling (f))", "X": 0})
    elif E >= trigger:
        out.update({"topup": False, "why": f"E {E} >= 1.03 x target {trigger:.1f}", "X": 0})
    else:
        X = math.ceil((C.TOPUP_MARGIN_TARGET * T - E) / (s * q["q"]))
        out.update({"topup": True, "X": int(X), "expected_rows_added": round(X * s * q["q"], 1),
                    "expected_E_after": round(E + X * s * q["q"], 1),
                    "why": f"E {E} < 1.03 x target {trigger:.1f}; X = ceil((1.06 x {T} - {E}) / ({s:.4f} x {q['q']}))"})
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--blocks", nargs="*", default=list(C.FAMILIES))
    ap.add_argument("--rebuilt", nargs="*", default=[], help="families whose CURRENT mixdev replaces the batch-4 file")
    ap.add_argument("--dev", nargs="*", default=[], metavar="FAM=PATH", help="analysis copies of mixdev files")
    ap.add_argument("--out", default=str(OUT_DEFAULT))
    ap.add_argument("--decide", action="store_true", help="also write A55_TOPUP_DECISION.json (the logged decision)")
    a = ap.parse_args(argv)
    t0 = time.time()
    over = dict(x.split("=", 1) for x in a.dev)
    files, drec = dev_files(a.rebuilt, over)
    dev, _fam_of = A.load_dev(files)
    st = A.a53_state(dev)
    b4 = batch4_units()
    out = {"method": __doc__, "created_utc": C.utc(), "dev_set": drec, "rebuilt": sorted(set(a.rebuilt) | set(over)),
           "blocks": {}, "topup": {}}
    for B in a.blocks:
        m = measure_block(B, dev, st, b4)
        out["blocks"][B] = m
        print(f"[{B}] N {m['rows']} target {m['target']} log-left {m['rows_left_batch4_log']} -> E {m['E']} "
              f"[{m['E_low']}..{m['E_high']}] binding {m['binding_units_batch4']}->{m['binding_units_now']} "
              f"self_check {m['self_check_ok']} ({m['wall_s']}s)", flush=True)
        if B in C.FAMILIES:
            out["topup"][B] = topup_decision(B, m)
    out["self_check_all"] = all(m["self_check_ok"] for m in out["blocks"].values())
    out["dev_not_batch4"] = sorted(f for f, r in drec.items() if r["status"].startswith(("CURRENT", "OVERRIDE")))
    out["wall_s"] = round(time.time() - t0, 1)
    Path(a.out).write_text(json.dumps(out, indent=1, default=str), encoding="utf-8")
    print("wrote", a.out, "self_check_all", out["self_check_all"], f"{out['wall_s']}s")
    if a.decide:
        rec = {"ruling": "A55 (e)", "logged_utc": C.utc(), "dev_set": drec, "decision": out["topup"],
               "measure_file": str(Path(a.out).name), "measure_sha256": C.sha_file(a.out),
               "note": "logged BEFORE any top-up row exists; X is never raised later; seed base 733,000,000 (fallback 743,000,000)"}
        DECISION.write_text(json.dumps(rec, indent=1, default=str), encoding="utf-8")
        print("wrote", DECISION)
    return 0


if __name__ == "__main__":
    sys.exit(main())
