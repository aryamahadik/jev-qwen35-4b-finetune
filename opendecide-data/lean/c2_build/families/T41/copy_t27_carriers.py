"""families/T41/copy_t27_carriers.py: one-off extraction of T27's frozen carrier templates into T41's own pool module.

READ-ONLY on families/T27/pools_v2/ (skins.json, packs.json). Writes only families/T41/carrier_bank.py (plain data:
carrier templates and the pack list), so T41 never imports or modifies T27's plugin or pool code.

A T27 carrier skin is a document layout with the placeholders {SOURCE} (the organisation) and the line slots
{cap|INFO}, {cap|REQ1}, {cap|JUST1}, {REQ2}, {cap|JUST2}. Here every line that holds one of the line slots is cut out
and the first of them becomes the marker @LINES@ (where T41's own generated lines go); {SOURCE} becomes @ORG@.
Templates with digits, currency signs, addresses or other braces are dropped, and so are long ones (token budget).

  ../../.venv/bin/python -B families/T41/copy_t27_carriers.py        (from lean/c2_build)
"""
from __future__ import annotations

import json
import pprint
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
T27 = HERE.parent / "T27" / "pools_v2"
OUT = HERE / "carrier_bank.py"
LINE_SLOT = re.compile(r"\{(?:cap\|)?(?:INFO|REQ1|REQ2|JUST1|JUST2)\}")
PER_REGISTER = 10
MAX_CHARS = 330


def convert(text: str) -> str | None:
    lines, out, marked = text.split("\n"), [], False
    for ln in lines:
        if LINE_SLOT.search(ln):
            prefix = re.match(r"^((?:agent: )|(?:Answer: )|(?:Update: ))?", ln).group(1) or ""
            if not marked:
                out.append(prefix + "@LINES@")
                marked = True
            continue
        out.append(ln)
    if not marked:
        return None
    t = "\n".join(out).replace("{SOURCE}", "@ORG@").replace("{poss|SOURCE}", "@ORG@'s")
    if re.search(r"[{}$@]|\d|https?:|www\.", t.replace("@LINES@", "").replace("@ORG@", "")):
        return None
    if len(t) > MAX_CHARS or t.count("@LINES@") != 1:
        return None
    return t


def main() -> None:
    skins = json.loads((T27 / "skins.json").read_text(encoding="utf-8"))["records"]
    packs = json.loads((T27 / "packs.json").read_text(encoding="utf-8"))["records"]
    by_reg: dict = {}
    # A45: a training carrier must not name a held-out pack's setting (e.g. "veterinary clinic"): that is a held-out value
    held_settings = [p["setting"].lower() for p in packs if p["held_out"]] + [n.lower() for p in packs if p["held_out"] for n in p["names"]]
    for r in sorted(skins, key=lambda r: r["piece_id"]):
        t = convert(r["text"])
        if t is None or any(h in t.lower() for h in held_settings):
            continue
        by_reg.setdefault(r["register"], {})
        by_reg[r["register"]].setdefault(t, r["piece_id"])
    bank = {}
    for reg, d in sorted(by_reg.items()):
        items = sorted(d.items(), key=lambda kv: kv[1])
        step = max(1, len(items) // PER_REGISTER)
        bank[reg] = [(pid, t) for t, pid in items[::step][:PER_REGISTER]]
    plist = [(p["pack_id"], p["setting"], list(p["names"]), bool(p["held_out"])) for p in packs]
    src = ['"""families/T41/carrier_bank.py: GENERATED by copy_t27_carriers.py from T27\'s frozen pools_v2 (read-only copy).',
           "",
           "CARRIER_TEMPLATES[register] = [(T27 piece id, template)]; templates hold @ORG@ (organisation) and @LINES@",
           "(one marker: T41's generated lines go there). PACKS = [(pack id, setting, [org names], held_out)].",
           'Nothing here is a gold source; it is document filler text. Do not edit by hand."""', ""]
    src.append("CARRIER_TEMPLATES = " + pprint.pformat(bank, width=118, sort_dicts=True))
    src.append("")
    src.append("PACKS = " + pprint.pformat(plist, width=118))
    src.append("")
    OUT.write_text("\n".join(src), encoding="utf-8")
    print({k: len(v) for k, v in bank.items()}, "packs", len(plist))


if __name__ == "__main__":
    main()
