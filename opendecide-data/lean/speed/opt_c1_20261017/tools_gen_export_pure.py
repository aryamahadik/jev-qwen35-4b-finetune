"""Generate oc1/export_pure.py = the pure (Modal-free) part of hosting/export_c1_merged.py, copied VERBATIM by ast.

Why: export_c1_merged imports `modal`, `modal_direct_host` and (on the laptop) `sglang_host`, whose payer guard only
allows the mahadika* free-credit accounts. The merge itself needs C1's PINNED35 stack (/opt/fastpath python), which has
no Modal client. So the functions below are cut out of the original file unchanged (the test compares their source text
with the original), a tiny `core` shim stands in for modal_direct_host (lean_import, sha256_file), and the file is run
inside /opt/fastpath/bin/python by oc1/export_driver.py.

  python tools_gen_export_pure.py            # writes oc1/export_pure.py
  python tools_gen_export_pure.py --check    # exits 1 when oc1/export_pure.py differs from a fresh extraction
"""
