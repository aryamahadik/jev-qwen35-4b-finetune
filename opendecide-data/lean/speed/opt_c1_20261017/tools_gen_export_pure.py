def _lean_import():
    p = "/root/lean" if Path("/root/lean", "decoder_io.py").exists() else str(Path(__file__).resolve().parents[3])
    if p not in sys.path:
        sys.path.insert(0, p)
    import decoder_io
    return decoder_io


def _sha256_file(p) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


core = SimpleNamespace(lean_import=_lean_import, sha256_file=_sha256_file)  # stands in for modal_direct_host
