def extract(src_path=SRC) -> str:
    text = Path(src_path).read_text()
    tree = ast.parse(text)
    segs = {}
    for node in tree.body:
        name = None
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
            want = ASSIGNS
        elif isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            name = node.name
            want = DEFS
        else:
            continue
        if name in want:
            segs[name] = ast.get_source_segment(text, node)
    missing = [n for n in ASSIGNS + DEFS if n not in segs]
    if missing:
        raise SystemExit(f"not found in {src_path}: {missing}")
    body = "\n\n".join([segs[n] for n in ASSIGNS] + [""]) + "\n"
    body += "\n\n".join(segs[n] for n in DEFS) + "\n"
    return HEADER + body


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    new = extract()
    if "--check" in argv:
        return 0 if OUT.exists() and OUT.read_text() == new else 1
    OUT.write_text(new)
    print(f"wrote {OUT} ({len(new.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
