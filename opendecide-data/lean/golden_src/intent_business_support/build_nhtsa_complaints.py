"""Build golden rows from NHTSA Office of Defects Investigation vehicle-safety complaints (received 2015-2019).

Source : https://static.nhtsa.gov/odi/ffdd/cmpl/COMPLAINTS_RECEIVED_2015-2019.zip (file layout: CMPL.txt in the same
         folder). The file is regenerated by NHTSA; this builder pins the snapshot it was built from by sha256
         (Last-Modified 2026-09-25, S3 version fgYacOUcpup8sw9EFGyI3QTIXLpHFKat) and refuses any other bytes.
Licence: US Government work, public domain - catalog.data.gov record 'NHTSA's Office of Defects Investigation (ODI) -
         Complaints - Complaints Flat File', License http://www.usa.gov/publicdomain/label/1.0/ (publisher NHTSA).
Texts  : complaint narratives (CDESCR) written by vehicle owners (web / mobile form, letters) or by NHTSA hotline
         staff from a phone call (narratives starting 'TL*'). Received 2015-2019, i.e. before LLM writing tools.
Labels : the complaint form's own check boxes / counts, entered by the complainant or hotline staff:
         CRASH ('was vehicle involved in a crash'), FIRE ('was vehicle involved in a fire'), INJURED (number injured).
         Consistency guards against form/narrative mismatch (regex, no model):
           yes rows need at least one non-hedged mention of the event in the narrative;
           no rows need every mention of the event to be hedged or negated ('almost hit', 'could catch fire',
           'no one was injured', 'fire hazard') or no mention at all. Mentions of other vehicles' events are dropped
           when unhedged. Rows failing a guard are dropped, never relabelled.
Tasks  : crash / fire / injury - yes/no each; one question per complaint (ODINO), vehicle complaints only, exact and
         near-exact duplicate narratives dropped; narratives with phone numbers, e-mails, URLs, street addresses or
         VINs dropped; staff edit stamps ('UPDATED 7/7/15*CN') stripped; about 60% of 'no' rows are hard (a hedged or negated mention).
Deterministic (seed 20261119).
"""
import collections
import io
import random
import re
import zipfile

import _ibs_common as C

KEY = "nhtsa_complaints"
SEED = 20261119
URL = "https://static.nhtsa.gov/odi/ffdd/cmpl/"
ZIP = "COMPLAINTS_RECEIVED_2015-2019.zip"
ZIP_SHA = "d8d95b377ad5e40f014c83030102f5c43b4cd7c0f804d4a66d4b6f4239e94f60"
LAYOUT_SHA = "84585b4ded99b0c45abc4a5dc86f85332ba0a6969d2d7d9b1247f10fc53e8f45"
LICENCE = ("US Government work, public domain (catalog.data.gov/dataset/nhtsas-office-of-defects-investigation-odi-"
           "complaints-complaints-flat-file: License http://www.usa.gov/publicdomain/label/1.0/, publisher NHTSA)")
DATASET = "NHTSA ODI complaints flat file (static.nhtsa.gov/odi/ffdd/cmpl/COMPLAINTS_RECEIVED_2015-2019.zip)"
CACHE = C.CACHE / "nhtsa"
N = {"crash": 1600, "fire": 1200, "injury": 1400}
HARD_SHARE = 0.6

QUESTIONS = {
    "crash": "Does this vehicle safety complaint report that the vehicle was actually involved in a crash?",
    "fire": "Does this vehicle safety complaint report that the vehicle actually caught fire?",
    "injury": "Does this vehicle safety complaint report that at least one person was actually injured?",
}
DEFS = {
    "crash": {
        "yes": ("The complaint says the vehicle actually collided in the incident it describes: it hit, or was hit "
                "by, another vehicle, an object or a person."),
        "no": ("The complaint reports no actual collision of this vehicle: only a defect, a near miss, a crash that "
               "could or might happen, or a crash that is explicitly denied."),
    },
    "fire": {
        "yes": "The complaint says the vehicle actually caught fire, burned or had flames.",
        "no": ("The complaint reports no actual fire in this vehicle: only smoke, a burning smell, overheating or "
               "melting, a fire that could happen, or a fire that is explicitly denied."),
    },
    "injury": {
        "yes": ("The complaint says at least one person was actually hurt in the incident (any injury, including "
                "burns, bruises or airbag injuries)."),
        "no": ("The complaint reports nobody hurt: it says no one was injured, only that someone could have been "
               "hurt, or it does not mention any injury."),
    },
}

EVENT = {
    "crash": re.compile(r"\b(CRASH\w*|COLLI(DE|DED|DES|DING|SION|SIONS)|ACCIDENTS?|WRECK(ED|S)?|REAR[- ]?END\w*|"
                        r"T[- ]?BONED|STRUCK|HIT (A|AN|THE|ANOTHER|MY|HIS|HER|SOME|ME|US)|RAN INTO|SLAMMED INTO|"
                        r"CRASHED INTO|TOTALL?ED)\b"),
    "fire": re.compile(r"\b(FIRE|FIRES|FLAMES?|ABLAZE|ENGULFED|IGNITED|BURST INTO|BURNED (UP|DOWN)|BURNT (UP|DOWN))\b"),
    "injury": re.compile(r"\b(INJUR\w*|HURT|HOSPITAL\w*|EMERGENCY ROOM|FRACTUR\w*|BROKEN (ARM|LEG|NOSE|WRIST|RIB|"
                         r"RIBS|BONE|BONES|HAND|FINGER|ANKLE|FOOT)|BRUIS\w*|CONCUSSION|WHIPLASH|LACERAT\w*|STITCHES|"
                         r"SPRAIN\w*|AMBULANCE)\b"),
}
# hedge cues, checked in short windows around each mention (the window size depends on the cue type)
NEG_NEAR = re.compile(r"\b(NO|NOT|NEVER|NOBODY|NONE|WITHOUT|AVOID(ED|ING)?|PREVENT(ED|ING)?|NARROWLY|"
                      r"\w+N'T|CANNOT)\b")                      # within 3 tokens before
MODAL_NEAR = re.compile(r"\b(ALMOST|NEARLY|COULD|WOULD|MIGHT|MAY|CAN|POTENTIAL(LY)?|POSSIBL[EY]|RISK|CHANCE|"
                        r"LIKELY|IF|FEAR|AFRAID)\b")              # within 5 tokens before
REPORTED = re.compile(r"\b(READ|HEARD|REPORTS|ONLINE|INTERNET|NEWS|FORUMS?|VIDEOS?)\b")  # within 6 tokens before
AFTER_NEAR = re.compile(r"\b(HAZARDS?|RISKS?|WAITING|NOT|NONE)\b")   # within 3 tokens after
BOILER = [re.compile(r"\*?\s*PARTS OF THIS DOCUMENT HAVE BEEN REDACTED.*$", re.S),
          re.compile(r"INFORMATION REDACTED PURSUANT TO THE FREEDOM OF INFORMATION ACT.*$", re.S)]
SMOKY = re.compile(r"\b(SMOKE|SMOKING|BURNING|MELT\w*|OVERHEAT\w*|SPARK\w*)\b")
# review fix: wider cue lists used ONLY to drop 'no' rows whose narrative describes the event in other words
# (e.g. INJURED=0 but 'I HAVE SUFFERED CUTS ON MY HAND'); a 'no' row with any unhedged cue is dropped, never relabelled
NO_GUARD = {
    "crash": re.compile(r"\b(ROLL(ED|S)? OVER|ROLLOVER|FLIPPED|SIDESWIP\w*|BUMPED (INTO|A|THE)|BACKED INTO|"
                        r"RAN OFF THE ROAD|WENT OFF THE ROAD|HIT (A|THE) (TREE|POLE|CURB|WALL|GUARD ?RAIL|DITCH|DEER|"
                        r"FENCE|MAILBOX|BARRIER|MEDIAN|BUILDING|GARAGE|POST|SIGN)|INTO (A|THE) (DITCH|TREE|POLE|WALL|"
                        r"CURB|GUARD ?RAIL|FENCE|BUILDING|GARAGE|HOUSE|MEDIAN|BARRIER)|IMPACT\w*|DAMAGED THE (FRONT|"
                        r"REAR|BUMPER|SIDE|DOOR|FENDER))\b"),
    "fire": re.compile(r"\b(CAUGHT FIRE|ON FIRE|FIREBALL|SMOLDER\w*|SMOULDER\w*|EXPLOD\w*|EXPLOSION)\b"),
    "injury": re.compile(r"\b(CUTS|CUT (MY|HIS|HER|THEIR|OUR)|BURNS|BURNED (MY|HIS|HER|THEIR|OUR)|BLEED\w*|BLOOD\w*|"
                         r"PAIN|PAINS|PAINFUL|SORE|SORENESS|STITCH\w*|DOCTORS?|MEDICAL (ATTENTION|TREATMENT|CARE|"
                         r"BILLS?)|BROKE (MY|HIS|HER|THEIR)|SWOLLEN|SWELLING|ABRASION\w*|X-?RAYS?|CHIROPRACT\w*|"
                         r"PHYSICAL THERAPY|POISON\w*|CARBON MONOXIDE|NAUSEA\w*|NAUSEOUS|DIZZ\w*|HEADACHES?|"
                         r"SPRAIN\w*|SCARS?|SCARRED|TREATED|SUFFER\w*|WOUND\w*|KILL\w*|DIED|DEATH|FATAL\w*)\b"),
}
FORM_ECHO = re.compile(r"\bCRASH:\s*(YES|NO|Y|N)\b|\bFIRE:\s*(YES|NO|Y|N)\b|NUMBER OF (INJURIES|DEATHS)")


PII = re.compile(r"\(\s*\d{3}\s*\)\s*\d{3}|\b\d{3}[-. ]\d{3}[-. ]\d{4}\b|@|HTTP|WWW\.|\bP\.?\s?O\.? BOX\b|"
                 r"\b\d{2,6} [A-Z0-9 ]{2,30} (ST|AVE|RD|BLVD|DR|LN|HWY|STREET|AVENUE|ROAD|DRIVE|LANE|COURT|CT|WAY|"
                 r"PKWY|PARKWAY|CIRCLE|PLACE|PL)\b|\b[A-HJ-NPR-Z0-9]{17}\b")


def clean(t):
    t = t.strip()
    t = re.sub(r"^TL\*\s*", "", t)
    for b in BOILER:
        t = b.sub("", t)
    t = re.sub(r"\bUPDATED \d{1,2}/\d{1,2}/\d{2,4}\s*\*\s*[A-Z]{1,4}\b", " ", t)  # staff edit stamps
    t = re.sub(r"\*\s*[A-Z]{2,3}\s*'?\s*$", " ", t.strip())  # trailing staff initials such as '*DT'
    return re.sub(r"\s+", " ", t).strip()


def mentions(task, text, rx=None):
    """Classify each event mention: (word, hedge_type or None, before, after). hedge_type in neg/modal/reported/after."""
    t = re.sub(r"\bWITHOUT (ANY )?WARNING\b", "SUDDENLY", text)  # 'without warning' is not a negation of the event
    t = re.sub(r"\b(ALMOST|NEARLY) (IMMEDIATELY|INSTANTLY|RIGHT AWAY)\b", "QUICKLY", t)  # timing, not a hedge
    out = []
    for m in (rx or EVENT[task]).finditer(t):
        toks = t[:m.start()].split()
        after = " ".join(t[m.end():].split()[:3])
        b3, b5, b6 = " ".join(toks[-3:]), " ".join(toks[-5:]), " ".join(toks[-6:])
        if NEG_NEAR.search(b3):
            h = "neg"
        elif MODAL_NEAR.search(b5):
            h = "modal"
        elif REPORTED.search(b6):
            h = "reported"
        elif AFTER_NEAR.search(after):
            h = "after"
        else:
            h = None
        out.append((m.group(0), h, b6, after))
    return out


def near_key(t):
    return " ".join(re.sub(r"[^A-Z ]+", " ", t).split()[:40])


def main():
    C.fetch(URL + ZIP, CACHE / ZIP, ZIP_SHA)
    C.fetch(URL + "CMPL.txt", CACHE / "CMPL.txt", LAYOUT_SHA)
    rng = random.Random(SEED)
    stats = collections.Counter()
    by_odi = {}
    with zipfile.ZipFile(CACHE / ZIP) as z:
        name = z.namelist()[0]
        with io.TextIOWrapper(z.open(name), encoding="latin-1") as f:
            for line in f:
                p = line.rstrip("\r\n").split("\t")
                assert len(p) == 51, len(p)
                if p[45] != "V":
                    continue
                odi = p[1]
                if odi in by_odi:  # one ODINO spans several component rows; flags are per complaint
                    continue
                by_odi[odi] = p
    stats["complaints"] = len(by_odi)

    # exact / near-exact duplicate narratives: keep the lowest ODINO
    seen_text, recs = set(), []
    for odi in sorted(by_odi, key=lambda x: int(x) if x.isdigit() else 0):
        p = by_odi[odi]
        t = clean(p[19])
        if not (120 <= len(t) <= 2000) or len(t.split()) < 20:
            stats["length_drop"] += 1
            continue
        if PII.search(t):  # phone numbers, e-mails, URLs, street addresses, VINs
            stats["pii_drop"] += 1
            continue
        if FORM_ECHO.search(t):  # narrative pastes the form fields ('CRASH:NO FIRE:NO NUMBER OF INJURIES:0')
            stats["form_echo_drop"] += 1
            continue
        k = near_key(t)
        if k in seen_text:
            stats["dup_drop"] += 1
            continue
        seen_text.add(k)
        recs.append((odi, p, t))
    rng.shuffle(recs)

    pools = {(task, lab, hard): [] for task in N for lab in ("yes", "no") for hard in (False, True)}
    for odi, p, t in recs:
        flags = {"crash": p[6] == "Y", "fire": p[8] == "Y", "injury": int(p[9] or 0) > 0}
        if p[6] not in "YN" or p[8] not in "YN":
            continue
        for task in N:
            ms = mentions(task, t)
            plain = [m for m in ms if m[1] is None]
            if flags[task]:
                if plain:
                    pools[(task, "yes", False)].append((odi, p, t, ms))
            else:
                if plain:
                    continue  # unhedged mention but the form says no -> inconsistent, drop
                if any(h is None for _, h, _, _ in mentions(task, t, NO_GUARD[task])):
                    stats[f"no_guard_drop_{task}"] += 1
                    continue  # event described in other words but the form says no -> drop
                hard = bool(ms) or (task == "fire" and bool(SMOKY.search(t)))
                pools[(task, "no", hard)].append((odi, p, t, ms))
    for k in sorted(pools):
        stats[f"pool_{k[0]}_{k[1]}_{'hard' if k[2] else 'plain'}"] = len(pools[k])

    rows, used = [], set()
    # scarcer tasks first so the rare yes pools are not consumed by another task
    for task in ("fire", "injury", "crash"):
        n = N[task] // 2
        take = {"yes": [], "no": []}
        for odi, p, t, ms in pools[(task, "yes", False)]:
            if len(take["yes"]) >= n:
                break
            if odi not in used:
                take["yes"].append((odi, p, t, ms, False))
                used.add(odi)
        n = len(take["yes"])
        n_hard = int(round(n * HARD_SHARE))
        for hard, quota in ((True, n_hard), (False, n - n_hard)):
            got = 0
            for odi, p, t, ms in pools[(task, "no", hard)]:
                if got >= quota:
                    break
                if odi not in used:
                    take["no"].append((odi, p, t, ms, hard))
                    used.add(odi)
                    got += 1
        # top up plain no rows if the hard pool ran short
        need = n - len(take["no"])
        for odi, p, t, ms in pools[(task, "no", False)]:
            if need <= 0:
                break
            if odi not in used:
                take["no"].append((odi, p, t, ms, False))
                used.add(odi)
                need -= 1
        m = min(len(take["yes"]), len(take["no"]))
        for lab in ("yes", "no"):
            for odi, p, t, ms, hard in take[lab][:m]:
                if lab == "no" and hard:
                    kinds = {h for _, h, _, _ in ms}
                    if "reported" in kinds:
                        edge = "reported_speech"
                    elif "modal" in kinds or "after" in kinds:
                        edge = "hypothetical"
                    elif "neg" in kinds:
                        edge = "negation"
                    else:
                        edge = "implicit"  # smoke / burning smell / overheating without fire
                elif len(t) > 1500:
                    edge = "long_context"
                else:
                    edge = None
                rows.append({
                    "key": KEY, "rid": f"odi{odi}_{task}", "state": f"Complaint narrative: {t}",
                    "instructions": QUESTIONS[task], "options": ["yes", "no"], "gold": lab, "soft": None,
                    "meta": {"dataset": DATASET, "config": f"PROD_TYPE=V, received 2015-2019; task={task}",
                             "revision": f"snapshot Last-Modified 2026-09-25; sha256 {ZIP}:{ZIP_SHA}",
                             "licence": LICENCE, "split": "train",
                             "orig_label": {"ODINO": odi, "CRASH": p[6], "FIRE": p[8], "INJURED": p[9],
                                            "COMPDESC": p[11], "LDATE": p[16], "CMPL_TYPE": p[20]},
                             "family": C.FAMILY, "edge": edge, "defs": task}})
    rng.shuffle(rows)
    C.write_rows(rows, KEY)
    for task in N:
        C.write_defs(DEFS[task], KEY, task)
    print(dict(stats))
    C.report(rows)


if __name__ == "__main__":
    main()
