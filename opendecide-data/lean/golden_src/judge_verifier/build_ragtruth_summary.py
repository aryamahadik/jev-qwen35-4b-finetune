"""Build raw rows for ragtruth_summary: is an LLM-written news summary faithful to its source article? (RAGTruth; Niu
et al., ACL 2024, "RAGTruth: A Hallucination Corpus for Developing Trustworthy Retrieval-Augmented Language Models").

Source : GitHub ParticleMedia/RAGTruth pinned to commit c103204b9ce28d6bbad859304bf30de72b8ed8fe,
         dataset/response.jsonl + dataset/source_info.jsonl; only responses with split == "train" and task_type ==
         "Summary" (CNN/Daily Mail articles and recent news) are used. The QA (MS MARCO passages) and Data2txt (Yelp
         business records) tasks are NOT used: their source texts come from corpora with non-commercial terms.
Licence: MIT (repo LICENSE at the pinned commit, "Copyright (c) 2023 Particle Media").
Texts  : news articles (human-written) and summaries generated by six LLMs (GPT-3.5/4, Llama-2 7/13/70B, Mistral-7B)
         - the objects being judged.
Labels : HUMAN word-level hallucination spans by trained annotators (four types: Evident Conflict, Subtle Conflict,
         Evident Baseless Info, Subtle Baseless Info; 'implicit_true' marks unsupported-but-true spans, which still
         count as unsupported by the source). faithful = no span; unfaithful = at least one span.
Rows   : at most two rows per article: one faithful and one unfaithful summary (different models), so the article is
         seen with a contrasting summary. Two framings (qids): 'sup' (fully supported?) and 'hal' (contains
         unsupported or conflicting content?). Responses flagged incorrect_refusal or truncated are dropped.
Review fixes: faithful (no-span) summaries are used only from GPT-4, GPT-3.5 and Llama-2-70B (the reviewer found
         unmarked hallucinations in about 1 in 3 'faithful' Llama-2-7B/13B summaries, e.g. an unsupported cause); a
         leading chat preamble line ('Sure! Here is the summary within 77 words:') is removed from every summary when
         no hallucination span lies in it, so the preamble is not a label cue.
Filters: decontamination (article + summary) against label-NLI, local train/dev/eval and JevBench; cross-check with
         other v14 parts; near-duplicate summaries dropped.
Deterministic (seed 20261208). CPU only.
"""
import collections
import json
import random
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _jv_common as C  # noqa: E402

KEY = "ragtruth_summary"
SEED = 20261208
COMMIT = "c103204b9ce28d6bbad859304bf30de72b8ed8fe"
BASE = f"https://raw.githubusercontent.com/ParticleMedia/RAGTruth/{COMMIT}/"
FILES = {"dataset/response.jsonl": "e4c2e4ac24fff676d8984cc61c35d791612fadc58015335d97dd632375e18073", "dataset/source_info.jsonl": "0dffc26ea9f3c1c3d7c7e8336b56ef1646e3cec876edffcca3c9c624d12d578b", "LICENSE": "b7fd7d6bdfe0cbba63c63a310914beb4a4acb8bf08da73849219f45385f5b244"}
LICENCE = (f"MIT (https://github.com/ParticleMedia/RAGTruth/blob/{COMMIT}/LICENSE, 'Copyright (c) 2023 Particle "
           "Media'); Summary task only (CNN/Daily Mail + recent news articles)")
DATASET = "ParticleMedia/RAGTruth (Summary task, train split)"
MAX_STATE = 9000
# review fix: a 'no span' label is trusted only for models whose summaries are mostly faithful (low base rate of
# hallucination, so a missed span is unlikely); for Llama-2-7B/13B and Mistral-7B the reviewer found about 1 in 3
# 'faithful' summaries with an unmarked unsupported claim (e.g. 'withdrawing ... due to the conflict in Ukraine').
FAITHFUL_MODELS = {"gpt-4-0613", "gpt-3.5-turbo-0613", "llama-2-70b-chat"}
PREAMBLE = re.compile(r"\A\s*(?:sure|here|certainly|okay|of course)\b[^\n]{0,160}:[ \t]*\n+", re.I)

Q = {
    "sup": "Is everything stated in the summary supported by the news article?",
    "hal": "Does the summary contain any claim that conflicts with the news article or is not supported by it?",
}
_SUP = ("Faithful: every claim in the summary is stated in or directly inferable from the article, with names, "
        "numbers, dates, attributions and certainty kept as the article gives them; omissions are fine.")
_HAL = ("Unfaithful: at least one claim contradicts the article (changed name, number, date, cause, who said what, "
        "certainty), or adds information the article does not contain, even if it is true in the real world or only "
        "a subtle overstatement.")
DEFS = {"sup": {"yes": _SUP, "no": _HAL}, "hal": {"yes": _HAL, "no": _SUP}}


def main():
    rng = random.Random(SEED)
    cache = C.CACHE / "ragtruth"
    paths = {rel: C.fetch(BASE + rel, cache / Path(rel).name, sha) for rel, sha in FILES.items()}
    src = {}
    for l in open(paths["dataset/source_info.jsonl"]):
        o = json.loads(l)
        if o["task_type"] == "Summary":
            src[o["source_id"]] = o
    stats = collections.Counter()
    by_src = collections.defaultdict(list)
    for l in open(paths["dataset/response.jsonl"]):
        r = json.loads(l)
        if r["source_id"] not in src:
            continue
        stats["summary_responses"] += 1
        if r["split"] != "train":
            stats["skip_test"] += 1
            continue
        if r["quality"] != "good":
            stats[f"drop_{r['quality']}"] += 1
            continue
        s = src[r["source_id"]]
        if not r["labels"] and r["model"] not in FAITHFUL_MODELS:
            stats["drop_faithful_weak_model"] += 1
            continue
        art = C.clean(s["source_info"] if isinstance(s["source_info"], str) else json.dumps(s["source_info"]))
        raw = r["response"]
        pm = PREAMBLE.match(raw)
        if pm and all(y["start"] >= pm.end() for y in r["labels"]):
            raw = raw[pm.end():]  # chat boilerplate line ('Sure! Here is the summary within 77 words:')
            stats["preamble_stripped"] += 1
        resp = C.clean(raw)
        if not resp or not art:
            continue
        state = f"News article:\n{art}\n\nSummary:\n{resp}"
        if len(state) > MAX_STATE:
            stats["drop_long"] += 1
            continue
        by_src[r["source_id"]].append({"rid": f"rt-{r['id']}", "sid": r["source_id"], "model": r["model"],
                                       "labels": r["labels"], "resp": resp, "art": art, "state": state,
                                       "source": s["source"]})
    core = {}
    for sid, lst in by_src.items():
        for x in lst:
            core[x["rid"]] = [x["art"], x["resp"]]
    hits = C.decon(core, cache_name=KEY)
    xhits = C.cross_v14({x["rid"]: [x["art"]] for lst in by_src.values() for x in lst}, own_keys={KEY})
    stats["decon_hits"], stats["xv14_hits"] = len(hits), len(xhits)

    sel = []
    for sid in sorted(by_src, key=int):
        lst = [x for x in by_src[sid] if x["rid"] not in hits and x["rid"] not in xhits]
        lst.sort(key=lambda x: x["rid"])
        rng.shuffle(lst)
        faith = [x for x in lst if not x["labels"]]
        unf = [x for x in lst if x["labels"]]
        if faith:
            sel.append(faith[0])
        if unf:
            # prefer a summary whose problem is not only an 'implicit_true' span
            unf.sort(key=lambda x: all(y.get("implicit_true") for y in x["labels"]))
            sel.append(unf[0])
    sel = C.near_dup_filter(sel, lambda x: x["resp"], thresh=0.9)
    n_f = sum(1 for x in sel if not x["labels"])
    n_u = len(sel) - n_f
    stats.update({"faithful": n_f, "unfaithful": n_u})
    # keep yes/no within 40-60%: trim the larger side
    faith = [x for x in sel if not x["labels"]]
    unf = [x for x in sel if x["labels"]]
    faith, unf = C.balance_yes(faith, unf, rng, lo=0.40, hi=0.60)
    rows = []
    for i, x in enumerate(sorted(faith + unf, key=lambda x: x["rid"])):
        qid = "sup" if rng.random() < 0.5 else "hal"
        ok = not x["labels"]
        gold = ("yes" if ok else "no") if qid == "sup" else ("no" if ok else "yes")
        types = sorted({y["label_type"] for y in x["labels"]})
        spans = " ".join(y["text"] for y in x["labels"])
        if not ok and re.search(r"\b(1[0-9]{3}|20[0-9]{2})\b|\b(monday|tuesday|wednesday|thursday|friday|saturday|"
                                r"sunday|january|february|march|april|may|june|july|august|september|october|"
                                r"november|december)\b", spans, re.I):
            e = "temporal"
        elif not ok and re.search(r"\d", spans):
            e = "numeric"
        elif not ok and any(t.startswith("Subtle") for t in types):
            e = "implicit"
        elif len(x["state"]) > 4000:
            e = "long_context"
        else:
            e = C.edge(x["resp"], order=("double_negation", "negation", "reported_speech"), default=None)
        rows.append({
            "key": KEY, "rid": x["rid"], "state": x["state"], "instructions": Q[qid], "options": C.YN, "gold": gold,
            "soft": None,
            "meta": {"dataset": DATASET, "config": f"dataset/response.jsonl (Summary; source={x['source']})",
                     "revision": f"git:{COMMIT}; sha256:{FILES['dataset/response.jsonl']}", "licence": LICENCE,
                     "split": "train",
                     "orig_label": {"source_id": x["sid"], "model": x["model"], "hallucination_types": types,
                                    "spans": [y["text"] for y in x["labels"]][:6],
                                    "implicit_true": [bool(y.get("implicit_true")) for y in x["labels"]][:6]},
                     "family": C.FAMILY, "edge": e, "defs": qid},
        })
    rng.shuffle(rows)
    C.write_outputs(KEY, rows, DEFS)
    st = C.summary(KEY, rows)
    print("stats:", dict(stats))
    print("types:", dict(collections.Counter(t for r in rows for t in r["meta"]["orig_label"]["hallucination_types"])))
    C.show_samples(rows, n=5, seed=18)
    C.append_manifest(C.manifest_record(
        KEY, DATASET, LICENCE, rows, "yesno",
        "News-summary faithfulness with HUMAN hallucination-span labels (conflict or baseless, evident or subtle; "
        "unsupported-but-true spans still count as unsupported); LLM-written summaries of CNN/DM and recent news; "
        "<= 2 summaries per article (one faithful, one not); QA (MS MARCO) and Data2txt (Yelp) parts rejected for "
        "source-text terms; two framings (supported? / conflicting-or-unsupported?).", st))


if __name__ == "__main__":
    main()
