"""rk_topics: Claude-written answer-key topics for gen_ranking's response-grading family.

Every topic is a question someone asked plus the facts an official answer key (policy, guide, instruction sheet)
gives.  Value facts ("V") have a slot with several possible values; which one is correct is drawn per item, so the
key must be read (nothing is world knowledge).  Yes/no facts ("B") have a true and a false wording.  'say' lists the
clause wordings a reply may use; 'eq' lists exactly equivalent renderings of a value (counts as correct).
All organisations are invented.  Values within one fact never contain one another as whole words.
"""


def V(fid, key, vals, say, eq=None):
    return dict(id=fid, kind="val", key=key, vals=vals, say=say, eq=eq or {})


def B(fid, key_t, key_f, say_t, say_f):
    return dict(id=fid, kind="bool", key_t=key_t, key_f=key_f, say_t=say_t, say_f=say_f)


