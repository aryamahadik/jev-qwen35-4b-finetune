def new_style(rng):
    ds = rng.randrange(6)
    ts = rng.randrange(3)
    return {"ds": ds, "dsb": ds if rng.random() < 0.6 else rng.randrange(6), "dsq": ds if rng.random() < 0.5 else rng.randrange(6),
            "ts": ts, "tsq": ts if rng.random() < 0.6 else rng.randrange(3), "qdt": rng.randrange(2),
            "cur": rng.choice(["$", "£", "€"]), "unit": rng.choice(["mph", "km/h"]), "hdr": rng.randrange(len(R.HDR)),
            "sep": rng.randrange(2), "sameday": False, "long": rng.random() < 0.2}


def setup(rng, dk):
    dom = DOM[dk]
    case = {"dom": dk, "st": new_style(rng), "qs": rng.randrange(10 ** 9)}
    if dom["gran"] == "day":
        b0 = rng.randint(dt.date(2024, 1, 8).toordinal(), dt.date(2027, 10, 15).toordinal())
        span = rng.randint(10, 45)
        lo, hi = b0, b0 + span
        ev_day = hi + rng.randint(2, 10)
        ent = dom["ent"](rng, {"event": dt.date.fromordinal(ev_day)})
        case.update(win=(lo, hi), dlo=lo - 2, dhi=(ev_day - 1) if dom["event"] else hi + 12)
        if dom["event"]:
            case["event_t"] = ev_day
    else:
        day = rng.randint(dt.date(2024, 1, 8).toordinal(), dt.date(2027, 10, 15).toordinal())
        if dk == "school":
            ent = dom["ent"](rng, {"event": dt.date.fromordinal(day + 1)})
            lo = day * 1440 + rng.randint(15 * 60, 19 * 60)
            hi = (day + 1) * 1440 + rng.randint(6 * 60, 7 * 60 + 15)
            case["event_t"] = (day + 1) * 1440 + 8 * 60
            case.update(win=(lo, hi), dlo=lo - 20, dhi=case["event_t"] - 1)
        else:
            ent = dom["ent"](rng, {"event": dt.date.fromordinal(day)})
            if dom["event"]:
                et = ent["etime"]
                back = rng.randint(90, 300) if dk == "ferry" else rng.randint(45, 150)
                lo = day * 1440 + max(5 * 60, et - back)
                hi = day * 1440 + et - rng.randint(2, 10)
                case["event_t"] = day * 1440 + et
                case.update(win=(lo, hi), dlo=lo - 10, dhi=case["event_t"] - 1)
            else:
                lo = day * 1440 + rng.randint(6 * 60, 9 * 60)
                cap_ = day * 1440 + (12 * 60 + 30 if dk == "flight_time" else 22 * 60)
                hi = min(cap_, lo + rng.randint(150, 540))
                case.update(win=(lo, hi), dlo=lo - 30, dhi=min(day * 1440 + 23 * 60 + 59, hi + 90))
            case["st"]["sameday"] = rng.random() < 0.5
    case["ent"] = ent
    vals = dom["vals"](rng)
    if dom["vtype"] == "num" and dom["numkind"] == "date":
        mid = (case["win"][0] + case["win"][1]) // 2
        vals = sorted(mid + o for o in vals)
    case["vals"] = vals
    return case


def sample_times(rng, lo, hi, k, gran):
    if hi - lo + 1 < k:
        return None
    if gran == "day":
        ts = sorted(rng.sample(range(lo, hi + 1), k))
        if k >= 2 and rng.random() < 0.06:  # occasionally two reports on the same day (a possible tie)
            i = rng.randrange(1, k)
            ts[i] = ts[i - 1]
        return ts
    return sorted(rng.sample(range(lo, hi + 1), k))


NO_TENTATIVE = ("addendum", "traffic order", "release notes")


def can_hold(src, kind, mood):
    """Which source types can plausibly carry a negative report, speculation or a question."""
    if src["style"] == "record" and (kind == "neg" or mood != "def"):
        return False
    if mood != "def" and src["docname"] in NO_TENTATIVE:
        return False
    return True


def pick_src(rng, dom, kind, mood="def"):
    idx = [i for i in range(len(dom["sources"])) if can_hold(dom["sources"][i], kind, mood)]
    return rng.choice(idx)


def gen_docs(rng, case):
    dom = DOM[case["dom"]]
    lo, hi = case["win"]
    gran = dom["gran"]
    allow = dom["allow"]
    vals = case["vals"]
    docs = []
    nid = [0]

    def mk(kind, src, pub, **kw):
        d = {"id": nid[0], "kind": kind, "src": src, "pub": pub, "mood": "def", "ent": 0, "v": None, "start": None,
             "end": None, "rel": None, "tgt": None, "inj": None, "sty": rng.randrange(10 ** 9), "surf": "pos"}
        d.update(kw)
        nid[0] += 1
        docs.append(d)
        return d

    long_ = case["st"]["long"]
    n_rep = rng.choice([3, 4, 5, 6] if long_ else [2, 2, 3, 3, 3, 4, 4, 5])
    pubs = sample_times(rng, lo, hi, n_rep, gran)
    if pubs is None:
        return None
    kinds_w = [("stmt", 0.45), ("neg", 0.12), ("sched", 0.22), ("temp", 0.13)]
    kinds_w = [(k, w) for k, w in kinds_w if k in allow]
    cur = rng.choice(vals)
    for i, p in enumerate(pubs):
        kind = "stmt" if i == 0 else rng.choices([k for k, _ in kinds_w], [w for _, w in kinds_w])[0]
        src = pick_src(rng, dom, kind)
        others = [x for x in vals if x != cur] or vals
        if kind == "stmt":
            v = cur if i == 0 or rng.random() < 0.25 else rng.choice(others)
            d = mk("stmt", src, p, v=v)
            if dom["vtype"] == "bin" and rng.random() < 0.25:
                d["surf"] = "negpres"
            cur = v
        elif kind == "neg":
            mk("neg", src, p, v=cur if rng.random() < 0.7 else rng.choice(vals))
        elif kind == "sched":
            v = rng.choice(others)
            if gran == "day":
                off = rng.choice([0, 1, 1, 2, 3, 4, 6, 8, 12])
                rel = ("today" if off == 0 else "tomorrow") if off in (0, 1) and rng.random() < 0.55 else None
                mk("sched", src, p, v=v, start=p + off, rel=rel)
            else:
                st = p + rng.choice([10, 15, 20, 30, 45, 60, 90])
                st -= st % 5
                if st <= p or st // 1440 != p // 1440:
                    mk("stmt", src, p, v=v)
                else:
                    mk("sched", src, p, v=v, start=st)
        else:  # temp (day domains only)
            tv = dom.get("temp_vals") or others
            v = rng.choice([x for x in tv if x in vals] or others)
            off = rng.choice([0, 1, 2, 3, 5, 7])
            ln = rng.choice([1, 2, 3, 4, 6, 9, 13])
            rel = ("today" if off == 0 else "tomorrow") if off in (0, 1) and rng.random() < 0.4 else None
            mk("temp", src, p, v=v, start=p + off, end=p + off + ln, rel=rel)
    reps = [d for d in docs if d["kind"] in REPORT_KINDS]
    if "corr" in allow and rng.random() < 0.28:
        cands = [d for d in reps if d["kind"] != "neg" and d["pub"] < hi]
        if cands:
            tg = rng.choice(cands)
            nv = [x for x in vals if x != tg["v"]]
            if tg["kind"] == "temp" and dom.get("temp_vals"):
                nv = [x for x in nv if x in dom["temp_vals"]]
            if nv:
                mk("corr", tg["src"], rng.randint(tg["pub"] + 1, hi), v=rng.choice(nv), tgt=tg["id"])
    if "retr" in allow and rng.random() < 0.2:
        taken = {d["tgt"] for d in docs if d["kind"] == "corr"}
        cands = [d for d in reps if d["id"] not in taken and d["pub"] < hi]
        if cands:
            tg = rng.choice(cands)
            mk("retr", tg["src"], rng.randint(tg["pub"] + 1, hi), tgt=tg["id"])
    n_dis = rng.choice([2, 3, 4] if long_ else [0, 1, 1, 2, 2, 3])
    for _ in range(n_dis):
        typ = rng.choices(["hedge", "ask", "other_ent", "other", "inject"], [22, 10, 22, 16, 30])[0]
        p = rng.randint(lo, hi)
        if typ == "hedge":
            mk("stmt", pick_src(rng, dom, "stmt", "hedge"), p, v=rng.choice(vals), mood="hedge")
        elif typ == "ask":
            mk("stmt", pick_src(rng, dom, "stmt", "ask"), p, v=rng.choice(vals), mood="ask")
        elif typ == "other_ent":
            k = "neg" if ("neg" in allow and rng.random() < 0.2) else "stmt"
            mk(k, pick_src(rng, dom, k), p, v=rng.choice(vals), ent=1)
        elif typ == "other":
            mk("other", rng.randrange(len(dom["sources"])), p)
        else:
            mk("inject", -1, p, injspec=inj_spec(rng, case))
    if rng.random() < 0.12:
        el = [d for d in docs if eligible(d)]
        if el:
            rng.choice(el)["inj"] = inj_spec(rng, case)
    if len(docs) < 3 or len(docs) > 11:
        return None
    return docs


def inj_spec(rng, case):
    dom = DOM[case["dom"]]
    t = rng.choices(["value", "yesno", "rule"], [55, 25, 20])[0]
    return {"t": t, "v": rng.choice(case["vals"]), "yn": rng.choice(["yes", "no"]),
            "src": rng.randrange(len(dom["sources"]))}


def gen_rule(rng, dom):
    n = len(dom["sources"])
    r = rng.random()
    if r < 0.45:
        return {"t": "latest"}
    if r < 0.80:
        rank = list(range(n)) if rng.random() < 0.75 else rng.sample(range(n), n)
        return {"t": "auth", "rank": rank}
    offi = [i for i, s in enumerate(dom["sources"]) if s["off"]]
    if offi and len(offi) < n and rng.random() < 0.6:
        cnt = offi
    else:
        cnt = sorted(rng.sample(range(n), rng.randint(1, n - 1)))
    return {"t": "only", "cnt": cnt, "ph": rng.randrange(2)}


def points(case, rng):
    dom = DOM[case["dom"]]
    pts = []
    for d in case["docs"]:
        offs = [-1, 0, 1] if dom["gran"] == "day" else [-rng.choice([1, 2, 5, 10]), 0, rng.choice([1, 3, 5, 15])]
        pts += [d["pub"] + o for o in offs]
        if d.get("start") is not None:
            pts += [d["start"] + o for o in offs]
        if d.get("end") is not None:
            pts += [d["end"], d["end"] + 1]
    lo, hi = case["win"]
    pts += [rng.randint(lo, hi) for _ in range(3)]
    return sorted({p for p in pts if case["dlo"] <= p <= case["dhi"]})


def choose_mode_and_date(rng, case):
    dom = DOM[case["dom"]]
    docs = case["docs"]
    case["mode"] = "known"
    case["K"] = None
    el = [d["pub"] for d in docs if eligible(d)]
    late = [d for d in docs if d["kind"] in ("corr", "retr") and el and d["pub"] > max(el)]
    if late and rng.random() < 0.5:
        c = rng.choice(late)
        lo = max(max(el), case["dlo"])
        hi = min(c["pub"] - 1, case["dhi"])
        if lo <= hi:
            case["D"] = rng.randint(lo, hi)
            if not dom["event"] and rng.random() < 0.35:
                case["mode"] = "pk"
                ks = [c["pub"], c["pub"] + rng.randint(0, 5)] + ([c["pub"] - 1] if c["pub"] - 1 > case["D"] else [])
                case["K"] = rng.choice(ks)
            else:
                case["mode"] = "hind"
            return True
    pts = points(case, rng)
    if not pts:
        return False
    case["D"] = rng.choice(pts)
    return True


def claim_candidates(case, rng, ev0):
    """All candidate claims with their verdicts (for the claim-based question types)."""
    dom = DOM[case["dom"]]
    vt = dom["vtype"]
    vals = case["vals"]
    r0 = ev0["r"]
    out = []
    from ec_core import truth_r, resolve, truth_diff_r
    for v in vals:
        out.append(({"t": "eq", "v": v}, truth_r(r0, {"t": "eq", "v": v}), 0.52 / len(vals)))
        if vt != "bin":
            out.append(({"t": "neq", "v": v}, truth_r(r0, {"t": "neq", "v": v}), 0.13 / len(vals)))
    if vt == "num":
        thrs = set(vals)
        sv = sorted(vals)
        for a, b in zip(sv, sv[1:]):
            mid = (a + b) // 2
            if dom["numkind"] == "time":
                mid -= mid % 5
            elif dom["numkind"] == "money":
                mid -= mid % (500 if dom["key"] in ("rent", "scholarship") else 25)
            elif dom["numkind"] == "pct":
                mid -= mid % 5
            elif dom["numkind"] == "speed":
                mid -= mid % 5
            if a < mid < b:
                thrs.add(mid)
        thrs = sorted(thrs)
        cands = [(op, x) for op, _ in dom["ops"] for x in thrs]
        for op, x in cands:
            c = {"t": "cmp", "op": op, "thr": x}
            out.append((c, truth_r(r0, c), 0.45 / len(cands)))
    if (not dom["event"] and vt != "bin" and case["mode"] == "known" and case.get("drop") is None):
        d2s = [p for p in points(case, rng) if p < case["D"]]
        rng.shuffle(d2s)
        for d2 in d2s[:4]:
            r1 = resolve(case, d2, d2)
            if not r1["ok"]:
                continue
            out.append(({"t": "diff", "D2": d2}, truth_diff_r(r1, r0), 0.08 / 4))
    return out


def trap_values(case):
    return {d["v"] for d in case["docs"] if d.get("v") is not None} | \
           {d["injspec"]["v"] for d in case["docs"] if d["kind"] == "inject" and d["injspec"]["t"] == "value"}


def build_base(rng, qid, dk):
    dom = DOM[dk]
    case = setup(rng, dk)
    e, c = case["ent"]["E"].lower(), case["ent"]["C"].lower()
    if e in c or c in e:
        return None
    docs = gen_docs(rng, case)
    if docs is None:
        return None
    case["docs"] = docs
    o = case["st"]["ord"] = rng.randrange(3)
    if o == 0:
        case["order"] = [d["id"] for d in sorted(docs, key=lambda d: (d["pub"], d["id"]))]
    elif o == 1:
        case["order"] = [d["id"] for d in sorted(docs, key=lambda d: (-d["pub"], d["id"]))]
    else:
        ids = [d["id"] for d in docs]
        rng.shuffle(ids)
        case["order"] = ids
    if dom["gran"] == "min" and case["st"]["sameday"]:
        days = {d["pub"] // 1440 for d in docs}
        case["st"]["sameday"] = len(days) == 1
    case["rule"] = gen_rule(rng, dom)
    case["qid"] = qid
    case["claim"] = None
    case["drop"] = None
    case["person"] = None
    case["pick_opts"] = None
    if not choose_mode_and_date(rng, case):
        return None
    if rng.random() < 0.06:
        cands = [d["id"] for d in docs if d["id"] not in {x["tgt"] for x in docs if x["kind"] in ("corr", "retr")}]
        if cands:
            case["drop"] = rng.choice(cands)
    if not valid(case):
        return None
    ev0 = evaluate(case)
    if not ev0["ok"]:
        return None
    if qid == "pick":
        opts = list(case["vals"]) + ["NEI"]
        rng.shuffle(opts)
        case["pick_opts"] = opts
    elif qid != "source":
        want_d = WANT[qid]
        want = rng.choices(list(want_d), list(want_d.values()))[0]
        cands = claim_candidates(case, rng, ev0)
        traps = trap_values(case)
        good = [(c, w * (2.0 if c.get("v") in traps else 1.0)) for c, vd, w in cands if vd == want]
        if not good:
            good = [(c, w) for c, vd, w in cands if (qid != "direct" or vd != N)]
        if not good:
            return None
        case["claim"] = rng.choices([c for c, _ in good], [w for _, w in good])[0]
        if qid in ("supported", "refuted") and rng.random() < 0.15 and case["claim"]["t"] != "diff":
            case["person"] = rng.choice(PERSONS).split()[0]
    if not valid(case):
        return None
    ev = evaluate(case)
    g = gold_of(case, ev)
    if g is None:
        return None
    return case, ev, g


# ------------------------------------------------------------------------------------------------ fact-flip twins
def mutations(case, rng):
    dom = DOM[case["dom"]]
    gran = dom["gran"]
    docs = case["docs"]
    targeted = {d["tgt"] for d in docs if d["kind"] in ("corr", "retr")}
    out = []
    D = case["D"]
    for d in docs:
        if gran == "day":
            deltas = [-7, -3, -2, -1, 1, 2, 3, 7]
        else:
            deltas = [-60, -30, -10, -5, -1, 1, 5, 10, 30, 60]
        news = {d["pub"] + x for x in deltas} | {D - 1, D, D + 1}
        if case["mode"] == "pk":
            news |= {case["K"], case["K"] + 1}
        for p in news:
            if p != d["pub"]:
                out.append(("doc", "pub", d["id"], p))
        if d["kind"] in REPORT_KINDS or d["kind"] == "corr":
            vs = case["vals"]
            tg = next((x for x in docs if x["id"] == d["tgt"]), None) if d["kind"] == "corr" else None
            if (d["kind"] == "temp" or (tg and tg["kind"] == "temp")) and dom.get("temp_vals"):
                vs = [v for v in vs if v in dom["temp_vals"]]
            for v in vs:
                if v != d["v"]:
                    out.append(("doc", "val", d["id"], v))
        if d["kind"] in ("sched", "temp"):
            for x in ([-2, -1, 1, 2] if gran == "day" else [-15, -5, 5, 15]):
                out.append(("doc", "start", d["id"], d["start"] + x))
            out.append(("doc", "start", d["id"], D))
            out.append(("doc", "start", d["id"], D + 1))
        if d["kind"] == "temp":
            for x in [-2, -1, 1, 2]:
                out.append(("doc", "end", d["id"], d["end"] + x))
            out.append(("doc", "end", d["id"], D))
            out.append(("doc", "end", d["id"], D - 1))
        if d["kind"] in REPORT_KINDS and d["id"] not in targeted:
            out.append(("doc", "ent", d["id"], 1 - d["ent"]))
            if d["kind"] == "stmt":
                for m in ("def", "hedge", "ask"):
                    if m != d["mood"]:
                        out.append(("doc", "mood", d["id"], m))
                if dom["vtype"] != "bin":
                    out.append(("doc", "kind", d["id"], "neg"))
            if d["kind"] == "neg":
                out.append(("doc", "kind", d["id"], "stmt"))
        if d["kind"] not in ("inject", "corr", "retr") and d["id"] not in targeted:
            for s in range(len(dom["sources"])):
                if s != d["src"]:
                    out.append(("doc", "src", d["id"], s))
    for p in points(case, rng):
        if p != D:
            out.append(("q", "D", None, p))
    c = case.get("claim")
    if c:
        if c["t"] in ("eq", "neq"):
            for v in case["vals"]:
                if v != c["v"]:
                    out.append(("q", "claim", None, dict(c, v=v)))
            if dom["vtype"] != "bin":
                out.append(("q", "claim", None, dict(c, t="neq" if c["t"] == "eq" else "eq")))
        elif c["t"] == "cmp":
            for op, _ in dom["ops"]:
                if op != c["op"]:
                    out.append(("q", "claim", None, dict(c, op=op)))
            for v in case["vals"]:
                if v != c["thr"]:
                    out.append(("q", "claim", None, dict(c, thr=v)))
        elif c["t"] == "diff":
            for p in points(case, rng):
                if p < D and p != c["D2"]:
                    out.append(("q", "claim", None, dict(c, D2=p)))
    rl = case["rule"]
    n = len(dom["sources"])
    alts = [{"t": "latest"}, {"t": "auth", "rank": list(range(n))}]
    offi = [i for i, s in enumerate(dom["sources"]) if s["off"]]
    if offi and len(offi) < n:
        alts.append({"t": "only", "cnt": offi, "ph": rl.get("ph", 0)})
    for a in alts:
        if a != rl:
            out.append(("q", "rule", None, a))
    if case["mode"] == "known":
        out.append(("q", "mode", None, "hind"))
    elif case["mode"] == "hind":
        out.append(("q", "mode", None, "known"))
    if case["mode"] == "pk":
        for k in (case["K"] - 1, case["K"] + 1, case["K"] + 3):
            out.append(("q", "K", None, k))
    for d in docs:
        if d["id"] != case.get("drop"):
            out.append(("q", "drop", None, d["id"]))
    if case.get("drop") is not None:
        out.append(("q", "drop", None, None))
    return out


def apply_mut(case, m):
    new = copy.deepcopy(case)
    lvl, what, did, val = m
    if lvl == "doc":
        d = next(x for x in new["docs"] if x["id"] == did)
        if what == "pub":
            delta = val - d["pub"]
            d["pub"] = val
            if d["kind"] in ("sched", "temp") and d.get("rel"):
                d["start"] += delta
                if d["kind"] == "temp":
                    d["end"] += delta
        elif what == "val":
            d["v"] = val
        elif what == "start":
            d["start"] = val
            d["rel"] = None
        elif what == "end":
            d["end"] = val
        elif what == "ent":
            d["ent"] = val
            if val == 1:
                d["inj"] = None
        elif what == "mood":
            d["mood"] = val
            if val != "def":
                d["inj"] = None
                d["surf"] = "pos"
        elif what == "kind":
            d["kind"] = val
            d["surf"] = "pos"
        elif what == "src":
            d["src"] = val
    else:
        if what == "D":
            new["D"] = val
        elif what == "claim":
            new["claim"] = val
        elif what == "rule":
            new["rule"] = val
        elif what == "mode":
            new["mode"] = val
        elif what == "K":
            new["K"] = val
        elif what == "drop":
            new["drop"] = val
    return new


def describe(case, m):
    lvl, what, did, val = m
    if lvl == "doc":
        d = next(x for x in case["docs"] if x["id"] == did)
        old = d.get({"val": "v"}.get(what, what))
        return {"field": what, "doc": case["order"].index(did) + 1, "from": old, "to": val}
    old = case.get(what) if what != "claim" else case["claim"]
    return {"field": what, "from": old, "to": val}


def make_twin(rng, case, gold0, want_gold=None):
    muts = mutations(case, rng)
    rng.shuffle(muts)
    ok_doc, ok_q = [], []
    for m in muts:
        new = apply_mut(case, m)
        if new["mode"] == "hind" and case["mode"] == "known":
            pass
        if not valid(new):
            continue
        ev = evaluate(new)
        g = gold_of(new, ev)
        if g is None or g == gold0:
            continue
        if want_gold is not None and g != want_gold:
            continue
        if new.get("claim") and new["claim"]["t"] == "diff" and new["mode"] != "known":
            continue
        (ok_doc if m[0] == "doc" else ok_q).append((m, new, ev, g))
        if len(ok_doc) >= 4 and len(ok_q) >= 2:
            break
    pool = ok_doc if (ok_doc and (not ok_q or rng.random() < 0.85)) else ok_q
    if not pool:
        return None
    return rng.choice(pool)


# ------------------------------------------------------------------------------------------------ edges / traps
def traps_of(case, ev):
    dom = DOM[case["dom"]]
    docs = [d for d in case["docs"] if d["id"] != case.get("drop")]
    cut = cutoff_of(case)
    t = case["D"]
    tr = set()
    for d in docs:
        late = cut is not None and d["pub"] > cut
        if late and (eligible(d) or d["kind"] in ("corr", "retr")):
            tr.add("future")
        if d["kind"] in ("corr", "retr") and late:
            tr.add("late_correction")
        if d["kind"] in ("corr", "retr") and not late:
            tr.add("corrected" if d["kind"] == "corr" else "retracted")
            if case["mode"] in ("hind", "pk") and d["pub"] > t:
                tr.add("hindsight_correction")
        if d["mood"] == "hedge":
            tr.add("hedge")
        if d["mood"] == "ask":
            tr.add("ask")
        if d["kind"] in REPORT_KINDS and d.get("ent") == 1:
            tr.add("other_entity")
        if d["kind"] == "other":
            tr.add("other_attr")
        if d["kind"] == "inject":
            tr.add("inject")
        if d.get("inj"):
            tr.add("inject_embedded")
        if eligible(d) and d.get("rel"):
            tr.add("relative_date")
        if eligible(d) and d.get("surf") == "negpres":
            tr.add("negpres")
        if eligible(d) and d["kind"] == "temp":
            tr.add("temp_window")
        if eligible(d) and (t in (d["pub"], d.get("start"), d.get("end")) or (d.get("end") is not None and t == d["end"] + 1)):
            tr.add("boundary")
    r = ev["r"]
    for rep in r["reps"]:
        if rep["start"] > t:
            tr.add("not_yet")
        if rep["end"] < t:
            tr.add("expired")
    res = ev["res"]
    cov_all = [rep for rep in r["reps"] if rep["start"] <= t <= rep["end"]]
    if case["rule"]["t"] == "only" and any(rep["src"] not in case["rule"]["cnt"] for rep in r["reps"]):
        tr.add("uncounted")
    if case["rule"]["t"] == "auth" and len({rep["src"] for rep in cov_all}) > 1:
        tr.add("outranked")
    if len({rep["sig"] for rep in cov_all}) > 1:
        tr.add("superseded")
    if res == "TIE":
        tr.add("tie")
    if res is None:
        tr.add("no_report")
    if res not in (None, "TIE") and res[0] == "neg":
        tr.add("negative_report")
    return sorted(tr)


def edges_of(case, ev, gold, state, instr, traps):
    dom = DOM[case["dom"]]
    c = case.get("claim")
    e = set()
    tr = set(traps)
    if tr & {"future", "not_yet", "expired", "boundary", "late_correction", "hindsight_correction", "relative_date"} or \
            case["mode"] != "known" or (c and c["t"] == "diff"):
        e.add("temporal")
    if tr & {"outranked", "uncounted", "superseded", "corrected", "tie"} or \
            len({(d["kind"] == "neg", d["v"]) for d in case["docs"] if eligible(d)}) > 1:
        e.add("conflicting_evidence")
    qid = case["qid"]
    if (c is not None and ev["verdict"] == N) or (qid == "pick" and case["pick_opts"][LETTERS.index(gold)] == "NEI") or \
            (qid == "source" and gold == "none"):
        e.add("missing_info")
    if (c and c["t"] == "neq") or tr & {"negative_report", "negpres"}:
        e.add("negation")
    if c and c["t"] == "neq" and (qid == "refuted" or "negative_report" in tr):
        e.add("double_negation")
    if "temp_window" in tr or (case["rule"]["t"] == "only" and case["rule"].get("ph") == 1):
        e.add("exception")
    if "relative_date" in tr or "negpres" in tr:
        e.add("implicit")
    if (c and c["t"] == "diff") or tr & {"retracted", "corrected"} or case.get("drop") is not None:
        e.add("multi_hop")
    if case.get("drop") is not None:
        e.add("hypothetical")
    if case.get("person"):
        e.add("reported_speech")
    else:
        w = ev["r"]["winA"]
        if len(w) == 1:
            wd = next(d for d in case["docs"] if d["id"] == w[0])
            if wd["kind"] != "inject" and dom["sources"][wd["src"]]["style"] == "call":
                e.add("reported_speech")
    if dom["vtype"] == "num" and (c and c["t"] == "cmp"):
        e.add("numeric")
    if dom["vtype"] == "num" and c and c["t"] in ("eq", "neq", "cmp"):
        st = case["st"]
        k = dom["numkind"]
        if (k == "time" and st["ts"] != st["tsq"]) or (k == "date" and st["dsb"] != st["dsq"]):
            e.add("units")
    if len(state) >= 2000:
        e.add("long_context")
    for x in e:
        assert x in EDGE_TAGS, x
    return ",".join(sorted(e)) if e else None


# ------------------------------------------------------------------------------------------------ rows
def make_row(case, ev, gold, rid, twin_of=None, changed=None):
    state = R.render_state(case)
    instr = R.question(case)
    traps = traps_of(case, ev)
    edge = edges_of(case, ev, gold, state, instr, traps)
    res = ev["res"]
    win = ev["r"]["winA"]
    orig = {"verdict": ev["verdict"], "resolved": res if res in (None, "TIE") else list(res),
            "winner_doc": [case["order"].index(w) + 1 for w in win], "rule": case["rule"]["t"], "mode": case["mode"],
            "claim": case.get("claim"), "traps": traps, "domain": case["dom"], "case": compact_case(case)}
    if changed:
        orig["changed"] = changed
    meta = {"dataset": "program generator golden_src/gen/gen_evidence_conflict.py",
            "config": f"{case['dom']}:{case['qid']}:{case['rule']['t']}:{case['mode']}", "revision": None,
            "licence": LICENCE, "split": "train", "orig_label": orig, "family": FAMILY, "edge": edge, "defs": case["qid"]}
    if twin_of:
        meta["twin_of"] = twin_of
    return {"key": KEY, "rid": rid, "state": state, "instructions": instr, "options": options_of(case), "gold": gold,
            "soft": None, "meta": meta}


DOC_DEFAULTS = {"mood": "def", "ent": 0, "v": None, "start": None, "end": None, "rel": None, "tgt": None, "inj": None,
                "surf": "pos"}


def compact_case(case):
    """The stored case (meta.orig_label.case) with default-valued document fields left out; ec_verify restores them."""
    c = {k: v for k, v in case.items() if v is not None}
    c["docs"] = [{k: v for k, v in d.items() if not (k in DOC_DEFAULTS and DOC_DEFAULTS[k] == v)} for d in case["docs"]]
    return json.loads(json.dumps(c))


def norm(x):
    import re
    return re.sub(r"\W+", " ", x.lower()).strip()


def upsert_manifest(rec):
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.touch(exist_ok=True)
    line = json.dumps(rec, ensure_ascii=False)
    with open(MANIFEST, "r+", encoding="utf-8") as f:
        fcntl.flock(f, fcntl.LOCK_EX)
        lines = f.read().splitlines()
        keep = []
        for ln in lines:
            try:
                if ln.strip() and json.loads(ln).get("key") == rec["key"]:
                    continue
            except Exception:  # noqa: BLE001
                pass
            keep.append(ln)
        keep.append(line)
        f.seek(0)
        f.write("\n".join(keep) + "\n")
        f.truncate()
        fcntl.flock(f, fcntl.LOCK_UN)


def source_rev():
    h = hashlib.sha256()
    for name in ("gen_evidence_conflict.py", "ec_core.py", "ec_render.py", "ec_domains.py", "ec_verify.py"):
        h.update((HERE / name).read_bytes())
    return "gen-v1+sha256:" + h.hexdigest()[:16]


def main():
    t0 = time.time()
    rng = random.Random(SEED)
    qids = list(QID_W)
    dkeys = [d["key"] for d in DOMAINS]
    rows = []
    seen_key, seen_state = set(), set()
    stats = collections.Counter()
    c3 = collections.Counter()
    idx = 0
    tries = 0
    dom_count = collections.Counter()
    while idx < N_PAIRS:
        tries += 1
        qid = rng.choices(qids, [QID_W[q] for q in qids])[0]
        # keep the domains balanced
        least = min(dom_count[k] for k in dkeys)
        dk = rng.choice([k for k in dkeys if dom_count[k] <= least + 3])
        b = build_base(rng, qid, dk)
        if b is None:
            stats["fail_base"] += 1
            continue
        case, ev, g = b
        want = None
        if qid == "choice3":
            tot = {"supported": c3["supported"], "refuted": c3["refuted"], "not enough information": c3["not enough information"]}
            others = [k for k in tot if k != g]
            want = min(others, key=lambda k: (tot[k], rng.random()))
        tw = make_twin(rng, case, g, want)
        if tw is None and want is not None:
            tw = make_twin(rng, case, g, None)
        if tw is None:
            stats["fail_twin:" + qid] += 1
            continue
        m, case2, ev2, g2 = tw
        rid = f"{KEY}-{idx:05d}"
        r1 = make_row(case, ev, g, rid)
        r2 = make_row(case2, ev2, g2, rid + "-twin", twin_of=rid, changed=describe(case, m))
        if r1["state"] == r2["state"] and r1["instructions"] == r2["instructions"]:
            stats["same_twin"] += 1
            continue
        ks = [norm(r["state"]) + "||" + norm(r["instructions"]) for r in (r1, r2)]
        sts = {norm(r1["state"]), norm(r2["state"])}
        if any(k in seen_key for k in ks) or any(s in seen_state for s in sts):
            stats["dup"] += 1
            continue
        seen_key.update(ks)
        seen_state.update(sts)
        rows += [r1, r2]
        if qid == "choice3":
            c3[g] += 1
            c3[g2] += 1
        dom_count[dk] += 1
        idx += 1
        stats["ok:" + qid] += 1
        stats["twin_" + m[0] + ":" + m[1]] += 1
        if idx % 1000 == 0:
            print(f"{idx} pairs, {tries} tries, {time.time() - t0:.0f}s", flush=True)
    print("pairs:", idx, "tries:", tries)
    for k, v in sorted(stats.items()):
        print(f"  {k}: {v}")

    # independent verification of every row (labels, rendering, per-document text checks)
    bad = ec_verify.verify_rows(rows)
    assert not bad, f"independent verifier disagreed on {len(bad)} rows: {bad[:5]}"
    print("independent verifier: all", len(rows), "rows agree")

    if os.environ.get("GEN_EC_DRY"):
        dry = Path(os.environ["GEN_EC_DRY"])
        with open(dry, "w", encoding="utf-8") as f:
            for r in rows:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
        print("dry run: wrote", dry)
        return
    rev = source_rev()
    for r in rows:
        r["meta"]["revision"] = rev
    RAW.mkdir(parents=True, exist_ok=True)
    DEFS.mkdir(parents=True, exist_ok=True)
    with open(RAW / f"{KEY}.jsonl", "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    for qid, d in DEFS_OUT.items():
        for k, v in d.items():
            assert len(v.split()) <= 48, (qid, k, len(v.split()))
        (DEFS / f"{KEY}__{qid}.json").write_text(json.dumps(d, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    summarize_and_manifest(rows)
    print(f"done in {time.time() - t0:.0f}s")


