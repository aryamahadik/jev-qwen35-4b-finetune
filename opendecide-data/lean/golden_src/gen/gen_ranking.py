"""Generator gen_ranking (family qa_decisions): best-of-N decisions under explicit criteria, weights and rules,
computed exactly from stated attributes.  Multiple choice only (3-11 options, every option defined).

Four program families (no dataset is read, no model is called; every text, rule, name and template is written by
Claude in golden_src/gen/rk_*.py; all organisations and people are invented):
  multi  (rk_multi.py + rk_domains.py) which bid / quote / plan / candidate / venue / flight ... should be chosen:
         24 realistic domains (IT procurement, catering, cleaning tenders, freight, SaaS, construction bids,
         translation, venues, movers, office leases, phone plans, energy tariffs, flights under a travel policy, hotels
         under a per-diem, community grants, research seed funds with judging panels, hiring panels, sports awards,
         support-agent awards, code patches, print jobs with bulk pricing, home insurance, school coach hire, flat
         rentals).  Mechanisms: weighted criteria (% / multipliers / points), lowest total cost (multi-part formulas,
         conditional add-ons, bulk-price tiers, per-period prices), points bands, best-value price ratios,
         lexicographic priority, judging panels (mean / median / trimmed mean / total), points formulas, first
         qualifying in order received.  Mandatory requirements (thresholds at the boundary, negated and
         double-negated wording, exceptions that relax or waive a requirement, deadlines), stated tie-break chains
         (some ending in a draw), distractor attributes no rule uses (incl. unused score columns), missing values
         with and without a stated missing-value rule (exact 'cannot be determined' by enumerating every possible
         value), printed corrections that override a cell, mixed units (per month vs per year, days vs weeks),
         hypothetical questions (withdrawal, dropped criterion, changed threshold, changed quantity).  Targets: first,
         second (reserve), last among the eligible.  11 candidate-block layouts x 4 rule styles x 4 wrappers.
  resp   (rk_resp.py + rk_topics.py) which reply / draft / response / answer meets an answer key best: 23 answer-key
         topics; rubrics 'correct and complete', points with penalties, essential points; equivalent wordings count,
         statements outside the key are ignored, self-contradictions count as contradictions.
  math   (rk_math.py) which worked answer is correct and complete (both requested values exact): 11 everyday
         calculations (bill split with tip, discount then tax, overtime, recipe scaling, journey time and arrival,
         fuel, paint tins with rounding up, simple interest, electricity bill, tiles and boxes, courier charges).
  vote   (rk_vote.py) which option a group adopts under a stated counting rule (plurality with tie-break, Borda,
         instant runoff, top-two runoff, approval) from grouped ballots; profiles prefer cases where the rule matters.
Every item has a FACT-FLIP TWIN (meta.twin_of): exactly one fact changes (one cell, one threshold, one quantity,
one judge's score, one statement in one reply, one value in the answer key, one number in the problem, one ballot
group's size or one adjacent swap in one ranking) and the gold option changes.
Self-check: every label is recomputed by rk_verify.py, an independent implementation (pairwise evaluator for multi;
text-level re-parsing for resp, math and vote); any disagreement aborts the build.  Deterministic (seed 20261302),
CPU only.  Output: data/v14_parts/raw/gen_ranking.jsonl + data/v14_parts/defs/gen_ranking__<qid>.json.
"""
