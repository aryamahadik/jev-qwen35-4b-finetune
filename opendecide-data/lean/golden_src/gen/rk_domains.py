"""rk_domains: Claude-written domain bank for gen_ranking's multi-attribute selection family.

Each domain lists the candidates' attributes (with units, display words and verb phrases for prose layouts), the
cost formula, which attributes may serve as mandatory requirements (gates, with optional exceptions), tie-breaks,
distractor attributes that no rule uses, and the selection mechanisms that make sense for it.  All organisations,
companies and people are invented.
"""


def money(key, hdr, lo, hi, step, prose, per="", minor=100, better="low", gnp=None, alt=None, cur=None):
    return dict(key=key, hdr=hdr, kind="money", lo=lo, hi=hi, step=step, prose=prose, per=per, minor=minor,
                better=better, gnp=gnp or f"a {hdr.lower()}", alt=alt, cur=cur)


def num(key, hdr, lo, hi, prose, u="", step=1, dp=0, better=None, gnp=None, alt=None, fmt=None):
    return dict(key=key, hdr=hdr, kind="num", lo=lo, hi=hi, step=step, prose=prose, u=u, dp=dp, better=better,
                gnp=gnp or f"a {hdr.lower()}", alt=alt, fmt=fmt)


def score(key, hdr, prose=None):
    return dict(key=key, hdr=hdr, kind="score", prose=prose or ("scored {v} for " + hdr.lower()))


def flag(key, hdr, vb, vb3, pt, pf, yes="Yes", no="No", p=0.7):
    return dict(key=key, hdr=hdr, kind="bool", vb=vb, vb3=vb3, pt=pt, pf=pf, yes=yes, no=no, p=p)


def cat(key, hdr, vals, prose):
    return dict(key=key, hdr=hdr, kind="cat", vals=vals, prose=prose)


