"""Generator gen_constraints (family qa_decisions): choose the one option that satisfies every hard constraint.

Program-generated, labels exact by construction; no dataset is read and no model is called.

What it makes
  * 29 real-world selection domains written by Claude (shipping services, meeting rooms, calendar slots across time
    zones, health plans, flights, suppliers, job candidates, apartments, hotels, rental cars, event venues, caterers,
    contractors, laptops, phone plans, course sections, clinic appointments, childcare, translators, movers, loans,
    cloud servers, trains, gyms, volunteers for a shift, parking garages, grant programs, used cars, software vendors)
    with invented company / product / person names.
  * each item: a request (context + 2-5 hard requirements + optional tie-break + optional nice-to-have) and 4-12
    options described in one of 9 formats (markdown / pipe / CSV / fixed-width / transposed tables, bullets, numbered
    lines, cards, prose); 8 layouts (brief, email, ticket, chat, policy, form fields, options-first, narrative) and
    2-3 domain context templates each (70+ surface templates before counting formats).
  * requirements: thresholds with inclusive vs strict wording (at most / under / by / before ...), negated modals
    ("must not cost more than"), double negation ("cannot come without tracking"), categories and exclusions, set
    quantifiers (both / all of / at least two of), exceptions ("..., unless parking is included, in which case up to
    $X is acceptable"), conditionals ("if a flight has a connection, the layover must be at least ..."), availability
    windows, accepted ranges (child age in months, guest counts), time zones, business days with holidays, calendar
    lead times, totals (nights x (rate + fee), unit price x quantity + setup, 12 x monthly), unit conversions
    (lb/kg, miles/km, m2/sq ft, TB/GB, m3/cu ft) whose verdict is robust to the exact factor, implicit facts from the
    context (party size, listed attendees, item value, applicant's age / credit score), unknown ("not stated") values
    that fail a requirement, unknown values in irrelevant columns that must not matter, and printed corrections that
    replace a listed value.
  * exactly one option meets every hard requirement, or the stated tie-break picks one among several (an exact tie is
    never generated), or - when the options include "none of the listed ..." - no option qualifies.  Near-miss options
    fail exactly one requirement, mostly right at the boundary; with a tie-break a near-miss often beats the winner
    on the tie-break key (an attractive distractor).
  * every item has a FACT-FLIP TWIN (meta.twin_of): one decisive fact changes (one option value, one requirement
    threshold / category / required item, the tie-break rule, a correction note, or a value becoming / ceasing to be
    unknown) so that the gold answer changes; both rows share every surface choice.

Self-check: every label is computed by the solver (cst_core.solve) and then recomputed by cst_verify.py, which parses
every displayed value back out of the rendered text, applies correction notes, re-evaluates all requirements with its
own evaluator, recomputes the tie-break, and checks the wording of every requirement (comparator direction after
negation, bool polarity, quantifier words, context facts, conversion notes).  Any disagreement aborts the run.
Deterministic (seed 20261302), CPU only.  Output: data/v14_parts/raw/gen_constraints.jsonl + defs/gen_constraints__<domain>.json
"""
import collections
import fcntl
import hashlib
import json
import os
import random
import re
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from cst_build import build_instance, con_attrs, make_twin  # noqa: E402
from cst_core import MISSING, NA  # noqa: E402
from cst_render import TABLE_FORMATS, draw_style, render, show_attrs  # noqa: E402
from cst_verify import verify  # noqa: E402

KEY = "gen_constraints"
FAMILY = "qa_decisions"
SEED = 20261302
N_PAIRS = int(os.environ.get("GEN_CONSTRAINTS_PAIRS", "6000"))
LEAN = HERE.parent.parent
RAW = LEAN / "data" / "v14_parts" / "raw"
DEFS = LEAN / "data" / "v14_parts" / "defs"
MANIFEST = LEAN / "golden_src" / "MANIFEST.jsonl"
LICENCE = "Generated by a Claude-written program in this repo (no third-party text or labels); CC0 1.0"
EDGE_ORDER = ["table", "numeric", "temporal", "units", "negation", "double_negation", "exception", "quantifier",
              "implicit", "multi_hop", "missing_info", "conflicting_evidence", "long_context"]


def load_domains():
    from cst_domains_a import DOMAINS_A
    doms = list(DOMAINS_A)
    try:
        from cst_domains_b import DOMAINS_B
        doms += DOMAINS_B
    except ImportError:
        pass
    try:
        from cst_domains_c import DOMAINS_C
        doms += DOMAINS_C
    except ImportError:
        pass
    return doms


def norm(t):
    return re.sub(r"\W+", " ", t.lower()).strip()


def definitions(D):
    if D.key in _DEFS_CACHE:
        return _DEFS_CACHE[D.key]
    out = {}
    for L in D.labels:
        out[L] = (f"{L} is correct only if its latest stated details meet every hard requirement (exactly at the "
                  f"limit passes 'at most', 'at least' or 'by' but fails 'under', 'over' or 'before'; an unstated detail "
                  f"fails) and it wins any stated tie-break.")
    out[D.none_label] = (f"Correct only when no listed {D.noun} meets every hard requirement on its latest stated "
                         f"details: each fails at least one, such as a value past a limit, a missing required feature, "
                         f"or a detail that is not stated.")
    for k, v in out.items():
        assert len(v.split()) <= 48, (D.key, k, len(v.split()))
    _DEFS_CACHE[D.key] = out
    return out


_DEFS_CACHE = {}


def edges_for(inst, st, state, n):
    tags = set()
    for c in inst["cons"]:
        tags |= set(c.tags)
    if inst["tie"]:
        tags |= set(inst["tie"].tags)
    if st["fmt"] in TABLE_FORMATS:
        tags.add("table")
    cols = inst["cols"]
    vals = [inst["shown"].get((i, a), inst["opts"][i].get(a)) for i in range(n) for a in cols]
    if any(v == MISSING for v in vals):
        tags.add("missing_info")
    if inst["notes"]:
        tags.add("conflicting_evidence")
    if n >= 10 or len(state) > 2500:
        tags.add("long_context")
    tags.discard("hypothetical")
    out = [t for t in EDGE_ORDER if t in tags]
    assert set(out) == tags, tags - set(out)
    return ",".join(out) if out else None


def summarize_cons(inst):
    out = []
    for c in inst["cons"]:
        nm = type(c).__name__
        d = {"type": nm, "id": c.cid}
        if nm == "CmpCon":
            d.update(attr=c.attr.key, op=c.op, thr=str(c.thr), pol=c.pol)
        elif nm == "BoolCon":
            d.update(attr=c.attr.key, want=c.want, form=c.form)
        elif nm == "CatCon":
            d.update(attr=c.attr.key, vals=list(c.vals), neg=c.neg)
        elif nm == "SetCon":
            d.update(attr=c.attr.key, mode=c.mode, items=list(c.items), k=c.k)
        else:
            d.update(attrs=list(c.attrs), params={k: str(v) for k, v in c.params.items()})
        out.append(d)
    return out


def make_rows(D, rng, idx):
    inst = build_instance(D, rng)
    if inst is None:
        return None, "build"
    r = make_twin(inst, rng)
    if r is None:
        return None, "twin"
    tw, desc = r
    n = len(inst["labels"])
    nice = None
    if inst["tie"] is None and tw["tie"] is None and D.nice and rng.random() < 0.3:
        used = con_attrs(inst) | con_attrs(tw)
        cands = [a for a in D.nice if a not in used]
        if cands:
            nice = rng.choice(cands)
    inst["nice"] = tw["nice"] = nice
    need = con_attrs(inst) | con_attrs(tw) | set(D.always)
    for x in (inst, tw):
        if x["tie"]:
            need |= set(x["tie"].attrs)
    free = [a.key for a in D.attrs if a.key not in need and not a.derived and (nice is None or a.key != nice)
            and a.key not in D.no_distract]
    extra = rng.sample(free, min(len(free), rng.choice([0, 1, 1, 2, 2, 3])))
    c1, c2 = show_attrs(inst, extra), show_attrs(tw, extra)
    cols = [a.key for a in D.attrs if a.key in set(c1) | set(c2)]
    inst["cols"] = tw["cols"] = cols
    if not (sense_ok(D, inst, cols) and sense_ok(D, tw, cols)):
        return None, "sense"
    st = draw_style(rng, D, len(inst["cons"]), n)
    vals = [x["shown"].get((i, a), x["opts"][i].get(a)) for x in (inst, tw) for i in range(n) for a in cols]
    st["force_missing_rule"] = any(v == MISSING for v in vals)
    rows = []
    rid0 = f"{KEY}-{D.key}-{idx:05d}"
    recs = []
    for j, x in enumerate((inst, tw)):
        state, question, rec = render(x, st)
        g = x["gold"]
        options = list(x["labels"]) + ([D.none_label] if x["none_opt"] else [])
        gold = D.none_label if g == "none" else x["labels"][g]
        near = sum(1 for i in range(n) if len([c for c in x["cons"]
                                              if not _met(c, x["opts"][i], x["ctx"])]) == 1)
        orig = {"answer": gold, "domain": D.key, "n_options": n, "n_requirements": len(x["cons"]),
                "tie_break": x["tie"].tid if x["tie"] else None, "qualifiers": len(x["Q"]), "none_option": x["none_opt"],
                "near_misses": near, "requirements": summarize_cons(x),
                "template": f"{st['layout']}/{st['fmt']}/ctx{st['ctx_i'] % len(D.contexts)}",
                "nice_to_have": nice, "corrections": len(x["notes"])}
        if j == 1:
            orig["changed"] = desc
        meta = {"dataset": "program generator golden_src/gen/gen_constraints.py (+ cst_*.py)",
                "config": f"{D.key}:{st['layout']}:{st['fmt']}", "revision": None, "licence": LICENCE, "split": "train",
                "orig_label": orig, "family": FAMILY, "edge": edges_for(x, st, state, n), "defs": D.key}
        if j == 1:
            meta["twin_of"] = rid0
        row = {"key": KEY, "rid": rid0 if j == 0 else rid0 + "-twin", "state": state, "instructions": question,
               "options": options, "gold": gold, "soft": None, "meta": meta}
        verify(x, st, state, rec, row)
        rows.append(row)
        recs.append(rec)
    assert rows[0]["gold"] != rows[1]["gold"], "twin gold unchanged"
    assert rows[0]["state"] != rows[1]["state"]
    return rows, None


def sense_ok(D, x, cols):
    """Common-sense guard (review fix): the gold option must not show a displayed detail that plainly rules it out in
    the real world even though no listed requirement mentions it (0 open seats / places, fewer volunteer hours left
    than the shift, a room free for less time than the booking, a caterer whose guest limits exclude the party, a
    supplier minimum order above the order size)."""
    g = x["gold"]
    if g == "none":
        return True
    o, ctx = x["opts"][g], x["ctx"]

    def val(a):
        v = o.get(a)
        return None if (v is None or a not in cols or (isinstance(v, str) and v in (MISSING, NA))) else v
    k = D.key
    if k == "course_section" and val("seats") == 0:
        return False
    if k == "childcare" and val("spots") == 0:
        return False
    if k == "volunteer" and val("hours") is not None and val("hours") < ctx["len"]:
        return False
    if k == "volunteer" and val("vfrom") is not None and val("vto") is not None and \
            val("vto") - val("vfrom") < 60 * ctx["len"]:
        return False
    if k == "meeting_room" and val("afrom") is not None and val("ato") is not None and \
            val("ato") - val("afrom") < ctx["dur"]:
        return False
    if k == "caterer" and ((val("ming") is not None and val("ming") > ctx["guests"]) or
                           (val("maxg") is not None and val("maxg") < ctx["guests"])):
        return False
    if k == "supplier" and val("moq") is not None and val("moq") > ctx["qty"]:
        return False
    return True


def _met(c, o, ctx):
    from cst_core import tv
    return tv(c.pred(), o, ctx) is True


def upsert_manifest(rec):
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.touch(exist_ok=True)
    line = json.dumps(rec, ensure_ascii=False)
    with open(MANIFEST, "r+", encoding="utf-8") as f:
        fcntl.flock(f, fcntl.LOCK_EX)
        lines = f.read().splitlines()
        keep = []
        for ln in lines:
            try:
                if ln.strip() and json.loads(ln).get("key") == rec["key"]:
                    continue
            except Exception:  # noqa: BLE001
                pass
            keep.append(ln)
        keep.append(line)
        f.seek(0)
        f.write("\n".join(keep) + "\n")
        f.truncate()
        fcntl.flock(f, fcntl.LOCK_UN)


def source_rev():
    h = hashlib.sha256()
    for p in sorted(HERE.glob("cst_*.py")) + [HERE / "gen_constraints.py"]:
        h.update(p.read_bytes())
    return "gen-v1+sha256:" + h.hexdigest()[:16]


def main():
    t0 = time.time()
    doms = load_domains()
    rng = random.Random(SEED)
    wsum = sum(D.weight for D in doms)
    quotas = {D.key: int(round(N_PAIRS * D.weight / wsum)) for D in doms}
    diff = N_PAIRS - sum(quotas.values())
    for D in doms[:abs(diff)]:
        quotas[D.key] += 1 if diff > 0 else -1
    rows, seen, seen_state = [], set(), set()
    fails = collections.Counter()
    idx = 0
    for D in doms:
        made, tries = 0, 0
        while made < quotas[D.key]:
            tries += 1
            assert tries < quotas[D.key] * 40 + 200, (D.key, made, fails)
            rr, why = make_rows(D, rng, idx)
            if rr is None:
                fails[(D.key, why)] += 1
                continue
            ks = [norm(r["state"]) + "||" + norm(r["instructions"]) for r in rr]
            if any(k in seen for k in ks) or any(norm(r["state"]) in seen_state for r in rr):
                fails[(D.key, "dup")] += 1
                continue
            seen.update(ks)
            seen_state.update(norm(r["state"]) for r in rr)
            rows += rr
            made += 1
            idx += 1
        print(f"{D.key}: {made} pairs ({tries} tries) {time.time() - t0:.0f}s", flush=True)
    print("fails:", dict(fails))
    rev = source_rev()
    for r in rows:
        r["meta"]["revision"] = rev
    check(rows, doms)
    RAW.mkdir(parents=True, exist_ok=True)
    DEFS.mkdir(parents=True, exist_ok=True)
    with open(RAW / f"{KEY}.jsonl", "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    for D in doms:
        (DEFS / f"{KEY}__{D.key}.json").write_text(json.dumps(definitions(D), indent=1, ensure_ascii=False) + "\n",
                                                   encoding="utf-8")
    summarize_and_manifest(rows, doms)
    print(f"done in {time.time() - t0:.0f}s")


def check(rows, doms):
    by = {D.key: D for D in doms}
    rids = set()
    for r in rows:
        assert set(r) == {"key", "rid", "state", "instructions", "options", "gold", "soft", "meta"}
        assert r["rid"] not in rids
        rids.add(r["rid"])
        assert r["gold"] in r["options"] and 3 <= len(r["options"]) <= 60
        assert r["state"].strip() and r["instructions"].strip()
        D = by[r["meta"]["defs"]]
        defs = definitions(D)
        assert all(o in defs for o in r["options"]), r["options"]
        if r["meta"].get("twin_of"):
            assert r["meta"]["twin_of"] in rids
    # class cap per domain (no label may exceed 50% of a domain's rows)
    per = collections.defaultdict(collections.Counter)
    for r in rows:
        per[r["meta"]["defs"]][r["gold"]] += 1
    for k, c in per.items():
        tot = sum(c.values())
        assert max(c.values()) / tot <= 0.5, (k, c.most_common(2))


def summarize_and_manifest(rows, doms):
    n = len(rows)
    print("rows", n)
    none_share = sum(r["gold"].startswith("none of the listed") for r in rows) / n
    print("gold = 'none of the listed ...':", round(none_share, 4))
    pos = collections.Counter()
    for r in rows:
        pos[r["options"].index(r["gold"]) / max(1, len(r["options"]) - 1)] += 0
        k = r["options"].index(r["gold"])
        pos["first" if k == 0 else "last" if k == len(r["options"]) - 1 else "middle"] += 1
    print("gold position:", {k: v for k, v in pos.items() if isinstance(k, str)})
    print("n options:", dict(sorted(collections.Counter(len(r["options"]) for r in rows).items())))
    print("by domain:", dict(collections.Counter(r["meta"]["defs"] for r in rows)))
    print("layouts:", dict(collections.Counter(r["meta"]["config"].split(":")[1] for r in rows)))
    print("formats:", dict(collections.Counter(r["meta"]["config"].split(":")[2] for r in rows)))
    tmpl = collections.Counter(r["meta"]["defs"] + "/" + r["meta"]["orig_label"]["template"].split("/")[2] + "/" +
                               r["meta"]["orig_label"]["template"].split("/")[0] for r in rows)
    ctxt = collections.Counter(r["meta"]["defs"] + "/" + r["meta"]["orig_label"]["template"].split("/")[2] for r in rows)
    print("distinct domain-context templates:", len(ctxt), "| distinct context x layout:", len(tmpl),
          "| distinct context x layout x format:",
          len({r["meta"]["defs"] + "/" + r["meta"]["orig_label"]["template"] for r in rows}))
    moves = collections.Counter(r["meta"]["orig_label"]["changed"]["move"] for r in rows if r["meta"].get("twin_of"))
    print("twin moves:", dict(moves))
    print("tie-break rows:", sum(r["meta"]["orig_label"]["tie_break"] is not None for r in rows),
          "none-option rows:", sum(r["meta"]["orig_label"]["none_option"] for r in rows))
    edges = collections.Counter(x for r in rows for x in (r["meta"]["edge"] or "").split(",") if x)
    print("edges:", dict(edges.most_common()))
    L = sorted(len(r["state"]) for r in rows)
    print("state chars min/med/max", L[0], L[len(L) // 2], L[-1])
    upsert_manifest({
        "key": KEY, "family": FAMILY,
        "dataset": "gen_constraints (program generator, golden_src/gen/gen_constraints.py + cst_*.py)",
        "licence": "CC0 1.0 (program-generated; Claude-written templates, vocabularies, rules and program; no third-party text or labels)",
        "rows": n, "qtype": "choice (pick the option meeting every hard requirement; 4-12 named options, some rows add "
                            "'none of the listed ...'; defs per domain: gen_constraints__<domain>.json)",
        "yesno_share": 0.0, "edge_tags": sorted(edges),
        "notes": (f"{len(doms)} real-world selection domains (shipping, meeting rooms, calendar slots with time zones, "
                  "health plans, flights, suppliers, candidates, apartments, hotels, rental cars, venues, caterers, "
                  "contractors, laptops, phone plans, course sections, clinic appointments, childcare, translators, "
                  "movers, loans, cloud servers, trains, gyms, volunteers, parking, grants, used cars, software vendors); "
                  "4-12 options in 9 formats x 8 layouts x 2-3 context templates per domain; exactly one option meets "
                  "every hard requirement, or a stated tie-break picks one (never an exact tie), or none qualifies when "
                  f"'none of the listed ...' is offered ({none_share:.1%} of rows); near-misses fail exactly one "
                  "requirement at the boundary (inclusive vs strict wording), attractive distractors win the tie-break "
                  "key but fail a requirement; negated / double-negated wording, exceptions (unless), conditionals, "
                  "set quantifiers, windows, ranges, time zones, business days + holidays, totals, unit conversions "
                  "(verdict robust to the exact factor), implicit context facts, unknown values, printed corrections. "
                  "Every row has a one-fact twin with a different gold (meta.twin_of). Every label re-derived by "
                  "cst_verify.py from the rendered text (values parsed back, corrections applied, own evaluator, "
                  "wording of every requirement checked): 0 disagreements. Review fixes: hotel rate requirements say "
                  "'nightly rate' (a nightly resort fee is listed separately); the venue tie-break names the deposit "
                  "percentage; availability-style details (open seats, places free, hours left, who can attend, "
                  "min/max guests, minimum order) are shown only when a requirement or tie-break uses them; a "
                  "common-sense guard rejects items whose gold shows a detail that plainly rules it out in practice.")})


if __name__ == "__main__":
    main()
