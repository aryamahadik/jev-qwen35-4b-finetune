def inner_available(op, t, s):
    n = op.name
    if n in ("val",):
        return has_inner(t.col(s["col"]), "eq")
    if n == "thr":
        c = t.col(s["col"])
        return ((s["rel"] + "_neg") in c.custom) or (not c.custom and s["rel"] in ("eq", "gt", "lt")) or \
            (s["rel"] in ("gt", "lt") and ("p_" + s["rel"]) not in c.custom and s["rel"] + "_neg" in c.custom)
    if n == "cmp":
        c = t.col(s["col"])
        if any(k.startswith("cmp_") for k in c.custom):
            return ("cmp_" + s["rel"] + "_neg") in c.custom
        return s["rel"] in ("gt", "lt", "eq")
    if n == "sup":
        c = t.col(s["col"])
        if ("sup_hi" if s["hi"] else "sup_lo") in c.custom:
            return ("sup_hi_neg" if s["hi"] else "sup_lo_neg") in c.custom
        return True
    if n == "catval":
        return True
    return False


def finish_spec(t, op, s, rng):
    s["tv"] = rng.randrange(10 ** 6)
    s["pfx"] = rng.randrange(len(PREFIX))
    s["words"] = rng.random() < 0.35
    if s.get("op") in ("count", "quant", "sum", "catcount", "only") and "sc" not in s:
        s["sc"] = scope_sfx(t, s, rng)
    key = s.get("col") or s.get("c2")
    if key and not key.startswith("_"):
        c = t.col(key)
        if c.conv and rng.random() < 0.5:
            s["alt"], s["altcol"] = rng.choice(c.conv), c.key
        elif c.kind == "time" and rng.random() < 0.35:
            s["alt"], s["altcol"] = ("12a" if t.style.get("time") == "24" else "24"), c.key
        elif c.kind == "date":
            s["alt"], s["altcol"] = rng.choice(["long_dmy", "long_mdy"]), c.key


def claim_text(op, t, s):
    x = op.text(t, s)
    if not x or "None" in x or "{" in x:
        return None
    neg = s.get("neg", 0)
    if neg == 2 or (neg == 1 and not s.get("inner")):
        x = PREFIX[s["pfx"]] + lc_claim(x)
    return x.rstrip(".") + "."


LEXNEG = re.compile(r"\b(not|no|none|never|nothing|nobody|neither|nor)\b|n't", re.I)


def edges_for(t, op, s, verdict, claim, state):
    tags = {"table"} | set(op.edges(t, s))
    neg = s.get("neg", 0)
    inner_txt = (op.text(t, s) if hasattr(op, "text") else op.question(t, s)) or ""
    lex = bool(LEXNEG.search(inner_txt))
    if neg or lex:
        tags.add("negation")
    if neg == 2 or (neg == 1 and not s.get("inner") and lex):
        tags.add("double_negation")
    if verdict == N:
        tags.add("missing_info")
    for k in ("col", "c1", "c2"):
        key = s.get(k)
        if key and not key.startswith("_") and key in {c.key for c in t.cols} and \
                any(t.v[e].get(key) is None for e in t.rows):
            tags.add("missing_info")
    if len(t.rows) >= 15 or len(state) > 1800:
        tags.add("long_context")
    if t.corr:
        tags.add("conflicting_evidence")
    order = ["table", "numeric", "units", "temporal", "quantifier", "negation", "double_negation", "exception",
             "missing_info", "conflicting_evidence", "multi_hop", "hypothetical", "implicit", "long_context"]
    return ",".join(x for x in order if x in tags)


SETTLED_OPS = ("count", "quant", "sup", "sum", "bool")


def settled_blank(t, op, s, rng, evalf, verdict):
    """Blank one cell the claim ranges over while the known values still settle it (the 'a blank is not always
    undecidable' edge case: e.g. 'at least 2' with 3 known hits, 'all above X' with a known violator)."""
    base = snap(t)
    cells = [(e, k) for (e, k) in dict.fromkeys(op.cells(t, s)) if e in t.v and not k.startswith("_")]
    rng.shuffle(cells)
    for (e, k) in cells[:8]:
        c = t.col(k)
        if not can_blank(t, e, c):
            continue
        t.v[e][k] = None
        if evalf(t) == verdict:
            return True
        restore(t, base)
    return False


def add_correction(t, op, s, rng, evalf, verdict):
    """Print a correction note for a decisive cell whose printed value would give the opposite verdict."""
    if op.name not in ("val", "thr", "cmp", "sup", "diff") or t.derive is not None or t.sort is not None:
        return False
    base = snap(t)
    cells = [(e, k) for (e, k) in op.cells(t, s) if e in t.v and not k.startswith("_")]
    rng.shuffle(cells)
    for (e, k) in cells[:4]:
        c = t.col(k)
        if c.virtual or c.kind in ("cat", "bool") or t.v[e].get(k) is None or c.nomiss:
            continue
        cur = t.v[e][k]
        for nv in cand_values(t, c, e, cur, op.consts(t, s), rng)[:25]:
            if nv == INF or nv in c.special:
                continue
            t.v[e][k] = nv
            t.corr[(e, k)] = cur
            if not t.is_valid() or evalf(t) != verdict:
                restore(t, base)
                continue
            saved = t.corr.pop((e, k))
            ign = evalf(t)
            t.corr[(e, k)] = saved
            if ign is not None and ign != verdict:
                return True
            restore(t, base)
    return False


# ------------------------------------------------------------------------------------------------ pair builders
def choose_domain(rng, qid):
    doms = list(BUILDERS)
    if qid == "pick":
        doms = [d for d in doms if d not in ("dosing", "shipping")]
    w = [BUILDERS[d][1] for d in doms]
    return rng.choices(doms, weights=w)[0]


def ops_for(t, need_n=False, need_qa=False):
    out = []
    for name, op in GENERIC.items():
        if need_n and not op.n_ok:
            continue
        if need_qa and not op.qa_ok:
            continue
        if op.applicable(t):
            out.append((op, OP_W[name]))
    for name in t.special:
        op = SPECIAL[name]
        if need_n and not op.n_ok:
            continue
        if need_qa and not op.qa_ok:
            continue
        if op.applicable(t):
            out.append((op, SPECIAL_W))
    return out


def verdict_plan(qid, rng):
    r = rng.random()
    if qid == "supported":
        b = T if r < 0.42 else (F if r < 0.80 else N)
        tw = {T: (F if rng.random() < 0.72 else N), F: T, N: T}[b]
    elif qid == "refuted":
        b = F if r < 0.42 else (T if r < 0.80 else N)
        tw = {F: (T if rng.random() < 0.72 else N), T: F, N: F}[b]
    elif qid == "enough":
        b = N if r < 0.5 else (T if r < 0.75 else F)
        tw = rng.choice([T, F]) if b == N else N
    else:  # choice3 (plans with N fail more often, so they are drawn more often)
        b, tw = rng.choices([(T, F), (F, T), (T, N), (N, T), (F, N), (N, F)], weights=[12, 12, 19, 19, 19, 19])[0]
    return b, tw


def gold_for(qid, v):
    if qid == "supported":
        return "yes" if v == T else "no"
    if qid == "refuted":
        return "yes" if v == F else "no"
    if qid == "enough":
        return "yes" if v in (T, F) else "no"
    if qid == "choice3":
        return VERD[v]
    if qid == "answer":
        return "yes" if v == T else "no"
    if qid == "answer_wrong":
        return "yes" if v == F else "no"
    raise ValueError(qid)


def claim_pair(rng, qid, dom):
    t0 = build_table(dom, rng)
    if t0 is None:
        return None
    b, tw = verdict_plan(qid, rng)
    need_n = N in (b, tw)
    if need_n and b == N and not (t0.partial or any(not c.nomiss and not c.virtual and c.key not in t0.derived
                                                    for c in t0.cols)):
        return None
    cands = ops_for(t0, need_n=need_n)
    if not cands:
        return None
    t = t0
    base0 = snap(t)
    for _ in range(12):
        restore(t, base0)
        op = rng.choices([o for o, _ in cands], weights=[w for _, w in cands])[0]
        r = rng.random()
        neg = (1 if r < 0.17 else (2 if r < 0.23 else 0)) if op.neg_ok else 0
        if neg == 2 and not op.inner_ok:
            neg = 1
        wb = final(b, neg)
        s = op.sample(t, rng, wb)
        if s is None:
            continue
        s["neg"] = neg
        finish_spec(t, op, s, rng)
        if neg:
            ia = inner_available(op, t, s)
            if neg == 2 and not ia:
                continue
            s["inner"] = ia and (neg == 2 or rng.random() < 0.5)
        evalf = lambda tt, s=s, op=op: final(op.eval(tt, s), s["neg"]) if op.eval(tt, s) is not None else None
        if evalf(t) != b:
            continue
        text_b = claim_text(op, t, s)
        if text_b is None:
            continue
        if b in (T, F) and op.name in SETTLED_OPS and rng.random() < 0.5:
            settled_blank(t, op, s, rng, evalf, b)
        if b in (T, F) and rng.random() < 0.15:
            add_correction(t, op, s, rng, evalf, b)
        sb = snap(t)
        # ---- twin
        s2, changed = None, None
        use_claim = (b in (T, F) and tw in (T, F) and hasattr(op, "mutate") and rng.random() < 0.3)
        if not use_claim:
            ed = table_edit(t, op, s, tw, evalf, rng, from_n=(b == N), to_n=(tw == N))
            if ed:
                s2, changed = s, ed
        if s2 is None and b in (T, F) and tw in (T, F):
            restore(t, sb)
            for _ in range(30):
                m = op.mutate(t, s, rng)
                if m is None:
                    continue
                if evalf_s(op, t, m) == tw and claim_text(op, t, m):
                    s2, changed = m, ("claim",)
                    break
        if s2 is None:
            continue
        st = snap(t)
        text_t = claim_text(op, t, s2)
        if text_t is None:
            continue
        restore(t, sb)
        if evalf(t) != b:
            continue
        return {"t": t, "op": op, "qid": qid, "specs": (s, s2), "snaps": (sb, st), "verdicts": (b, tw),
                "texts": (text_b, text_t), "changed": changed, "dom": dom}
    return None


def evalf_s(op, t, s):
    v = op.eval(t, s)
    return None if v is None else final(v, s.get("neg", 0))


def answer_pair(rng, qid, dom):
    t = build_table(dom, rng)
    if t is None:
        return None
    cands = ops_for(t, need_qa=True)
    if not cands:
        return None
    b = T if rng.random() < 0.5 else F
    tw = F if b == T else T
    base0 = snap(t)
    for _ in range(14):
        restore(t, base0)
        op = rng.choices([o for o, _ in cands], weights=[w for _, w in cands])[0]
        s = op.sample(t, rng, b)
        if s is None:
            continue
        s["neg"] = 0
        finish_spec(t, op, s, rng)
        if op.eval(t, s) != b:
            continue
        qa = op.qa(t, s)
        if qa is None:
            continue
        sb = snap(t)
        evalf = lambda tt, s=s, op=op: (op.eval(tt, s) if op.qa(tt, s) is not None else None)
        s2, changed = None, None
        if rng.random() < 0.55:
            ed = table_edit(t, op, s, tw, evalf, rng, False, False)
            if ed:
                s2, changed = s, ed
        if s2 is None:
            restore(t, sb)
            for _ in range(30):
                m = op.mutate(t, s, rng)
                if m is not None and op.eval(t, m) == tw and op.qa(t, m) is not None and op.qa(t, m)[1] != qa[1]:
                    s2, changed = m, ("claim",)
                    break
        if s2 is None:
            continue
        st = snap(t)
        qa2 = op.qa(t, s2)
        if qa2 is None:
            continue
        restore(t, sb)
        return {"t": t, "op": op, "qid": qid, "specs": (s, s2), "snaps": (sb, st), "verdicts": (b, tw),
                "texts": (qa, qa2), "changed": changed, "dom": dom}
    return None


def pick_pair(rng, dom):
    t = build_table(dom, rng)
    if t is None:
        return None
    base0 = snap(t)
    for _ in range(12):
        restore(t, base0)
        op = rng.choice(PICKS)
        s = op.sample(t, rng)
        if s is None:
            continue
        s["neg"] = 0
        finish_spec(t, op, s, rng)
        a = op.answer(t, s)
        if a is None:
            continue
        sb = snap(t)
        s2, changed = None, None
        if op.name != "pick_val":
            others = [e for e in s["cands"] if e != a]
            rng.shuffle(others)
            for tgt in others[:2]:
                ed = table_edit(t, op, s, tgt, lambda tt, s=s, op=op: op.answer(tt, s), rng, False, False)
                if ed:
                    s2, changed = s, ed
                    break
                restore(t, sb)
        else:
            m = op.mutate(t, s, rng)
            if m is not None and op.answer(t, m) not in (None, a):
                s2, changed = m, ("claim",)
        if s2 is None:
            continue
        st = snap(t)
        a2 = op.answer(t, s2)
        restore(t, sb)
        if a2 is None or a2 == a:
            continue
        return {"t": t, "op": op, "qid": "pick", "specs": (s, s2), "snaps": (sb, st), "verdicts": (a, a2),
                "texts": (op.question(t, s), op.question(t, s2)), "changed": changed, "dom": dom}
    return None


# ------------------------------------------------------------------------------------------------ rendering rows
def render_pair(P, rng, idx):
    t, op, qid = P["t"], P["op"], P["qid"]
    rows = []
    rid0 = f"{KEY}-{idx:05d}"
    s0 = P["specs"][0]
    prefixed = s0.get("neg", 0) == 2 or (s0.get("neg", 0) == 1 and not s0.get("inner"))
    place_instr = (qid in ("supported", "refuted", "enough") and P["changed"][0] != "claim" and not prefixed
                   and rng.random() < 0.3)
    qv = rng.randrange(1000)
    lab = rng.choice(CLAIM_LABELS)
    for j in range(2):
        s, sn, v, txt = P["specs"][j], P["snaps"][j], P["verdicts"][j], P["texts"][j]
        restore(t, sn)
        if qid == "pick":
            q = txt
            opts = LETTERS[:len(s["cands"])]
            tail = "Question: " + q + "\n" + "\n".join(f"({L}) {cap(t.ent.r(e))}" for L, e in zip(opts, s["cands"]))
            state = render_state(t, tail)
            ins = Q["pick"][qv % len(Q["pick"])]
            gold = opts[s["cands"].index(v)]
            options = list(opts)
            orig = {"answer": v, "op": op.name, "domain": P["dom"]}
            claim = q
        elif qid in ("answer", "answer_wrong"):
            q, a = txt
            state = render_state(t, f"Question: {q}\nProposed answer: {a}")
            ins = Q[qid][qv % len(Q[qid])]
            gold = gold_for(qid, v)
            options = ["yes", "no"]
            orig = {"proposed_answer_correct": v == T, "op": op.name, "domain": P["dom"]}
            claim = q + " " + a
        else:
            claim = txt
            if place_instr:
                tl = Q[qid + "_i"]
                ins = tl[qv % len(tl)].format(c=lc_claim(claim.rstrip(".")))
                state = render_state(t, "").rstrip()
            else:
                ins = Q[qid][qv % len(Q[qid])]
                state = render_state(t, f"{lab}: {claim}")
            gold = gold_for(qid, v)
            options = ["yes", "no"] if qid != "choice3" else ["supported", "refuted", "not enough information"]
            orig = {"verdict": VERD[v], "op": op.name, "domain": P["dom"], "negation": s.get("neg", 0)}
        if j == 1:
            orig["changed"] = P["changed"][0]
        edge = edges_for(t, op, s, v if qid not in ("pick",) else None, claim, state)
        meta = {"dataset": "program generator golden_src/gen/gen_tables.py", "config": f"{P['dom']}:{qid}:{op.name}",
                "revision": None, "licence": LICENCE, "split": "train", "orig_label": orig, "family": FAMILY,
                "edge": edge, "defs": qid}
        if j == 1:
            meta["twin_of"] = rid0
        rows.append({"key": KEY, "rid": rid0 if j == 0 else rid0 + "-twin", "state": state, "instructions": ins,
                     "options": options, "gold": gold, "soft": None, "meta": meta})
    restore(t, P["snaps"][0])
    return rows


# ------------------------------------------------------------------------------------------------ self-check (internal)
def recheck(P):
    """Re-evaluate both members of the pair on their stored table states with the generator's evaluator."""
    t, op, qid = P["t"], P["op"], P["qid"]
    for j in range(2):
        restore(t, P["snaps"][j])
        s = P["specs"][j]
        if qid == "pick":
            assert op.answer(t, s) == P["verdicts"][j]
        elif qid in ("answer", "answer_wrong"):
            assert op.eval(t, s) == P["verdicts"][j] and op.qa(t, s) == P["texts"][j]
        else:
            assert evalf_s(op, t, s) == P["verdicts"][j]
            assert claim_text(op, t, s) == P["texts"][j]
    restore(t, P["snaps"][0])


# ------------------------------------------------------------------------------------------------ output helpers
def norm(x):
    return re.sub(r"\W+", " ", x.lower()).strip()


def upsert_manifest(rec):
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.touch(exist_ok=True)
    line = json.dumps(rec, ensure_ascii=False)
    with open(MANIFEST, "r+", encoding="utf-8") as f:
        fcntl.flock(f, fcntl.LOCK_EX)
        lines = f.read().splitlines()
        keep = []
        for ln in lines:
            try:
                if ln.strip() and json.loads(ln).get("key") == rec["key"]:
                    continue
            except Exception:  # noqa: BLE001
                pass
            keep.append(ln)
        keep.append(line)
        f.seek(0)
        f.write("\n".join(keep) + "\n")
        f.truncate()
        fcntl.flock(f, fcntl.LOCK_UN)


def source_rev():
    h = hashlib.sha256()
    for name in ("gen_tables.py", "tab_core.py", "tab_ops.py", "tab_domains.py", "tab_verify.py"):
        h.update((HERE / name).read_bytes())
    return "gen-v1+sha256:" + h.hexdigest()[:16]


def main():
    t0 = time.time()
    rng = random.Random(SEED)
    qids = list(QID_W)
    pairs, rows = [], []
    seen_state, seen_key = set(), set()
    stats = collections.Counter()
    idx = 0
    tries = 0
    while len(pairs) < N_PAIRS:
        tries += 1
        qid = rng.choices(qids, weights=[QID_W[q] for q in qids])[0]
        dom = choose_domain(rng, qid)
        if qid == "pick":
            P = pick_pair(rng, dom)
        elif qid in ("answer", "answer_wrong"):
            P = answer_pair(rng, qid, dom)
        else:
            P = claim_pair(rng, qid, dom)
        if P is None:
            stats["fail:" + qid] += 1
            continue
        recheck(P)
        rr = render_pair(P, rng, idx)
        ks = [norm(r["state"]) + "||" + norm(r["instructions"]) for r in rr]
        if rr[0]["state"] == rr[1]["state"] and rr[0]["instructions"] == rr[1]["instructions"]:
            stats["same_twin"] += 1
            continue
        if any(k in seen_key for k in ks) or any(norm(r["state"]) in seen_state for r in rr):
            stats["dup"] += 1
            continue
        seen_key.update(ks)
        seen_state.update(norm(r["state"]) for r in rr)
        P["rows"] = rr
        pairs.append(P)
        rows += rr
        idx += 1
        stats["ok:" + qid] += 1
        if idx % 1000 == 0:
            print(f"{idx} pairs, {tries} tries, {time.time() - t0:.0f}s", flush=True)
    print("pairs:", len(pairs), "tries:", tries, dict(sorted(stats.items())))

    # independent verification on the rendered text
    import tab_verify
    bad = tab_verify.verify_pairs(pairs)
    if bad:
        ids = {b[0] for b in bad}
        for P in pairs:
            for j, r in enumerate(P["rows"]):
                if r["rid"] in ids:
                    print("=" * 90)
                    print(r["rid"], r["meta"]["config"], r["gold"], P["changed"], P["verdicts"])
                    print({k: v for k, v in P["specs"][j].items() if k != "tv"})
                    print(r["state"])
                    print("Q:", r["instructions"])
    assert not bad, f"independent verifier disagreed on {len(bad)} rows: {bad[:5]}"

    rev = source_rev()
    for r in rows:
        r["meta"]["revision"] = rev
    RAW.mkdir(parents=True, exist_ok=True)
    DEFS.mkdir(parents=True, exist_ok=True)
    with open(RAW / f"{KEY}.jsonl", "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    for qid, d in DEFS_OUT.items():
        for k, v in d.items():
            assert len(v.split()) <= 48, (qid, k, len(v.split()))
        (DEFS / f"{KEY}__{qid}.json").write_text(json.dumps(d, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    summarize_and_manifest(rows)
    print(f"done in {time.time() - t0:.0f}s")


