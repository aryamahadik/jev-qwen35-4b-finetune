def snap(t):
    return ({e: dict(r) for e, r in t.v.items()}, list(t.rows), dict(t.corr), list(t.pool))


def restore(t, sn):
    t.v = {e: dict(r) for e, r in sn[0].items()}
    t.rows = list(sn[1])
    t.corr = dict(sn[2])
    t.pool = list(sn[3])


def build_table(dom, rng):
    for _ in range(20):
        t = BUILDERS[dom][0](rng)
        if t is not None and t.is_valid():
            return t
    return None


def cand_values(t, c, e, cur, consts, rng):
    if c.kind in ("cat", "bool"):
        pool = list(c.cats or []) + [t.v[x].get(c.key) for x in t.rows]
        return [v for v in dict.fromkeys(pool) if v is not None and v != cur]
    st = max(1, c.step)
    vals = []
    for k, v in consts:
        if k == c.key and v is not None and v != INF and is_int(v):
            v = int(v)
            vals += [v, v - 1, v + 1, v - st, v + st]
    for x in t.rows:
        o = t.v[x].get(c.key) if x != e else None
        if o is not None and o != INF and is_int(o):
            vals += [o, o + st, o - st]
    if cur is not None and cur != INF:
        vals += [cur + d * st for d in (1, -1, 2, -2, 3, -3, 5, -5, 10, -10, 20, -20, 50, -50)]
    if c.kind not in ("date", "time"):
        for _ in range(4):
            vals.append(rng.randrange(c.gen_lo, c.hi + 1, st) if c.hi > c.gen_lo else c.gen_lo)
    vals += list(c.special)
    if c.unl:
        vals.append(INF)
    out = []
    span = max(1, c.hi - c.gen_lo)
    for v in dict.fromkeys(vals):
        if v == cur or v is None:
            continue
        if v != INF and v not in c.special and c.step > 1 and c.kind not in ("date",) and v % c.step:
            continue
        if v != INF and v not in c.special:
            if c.kind == "date":
                if not (693000 < v < 750000):
                    continue
                if cur is not None and cur not in c.special and abs(v - cur) > 4000:
                    continue
            elif c.kind == "time":
                if not (0 <= v < (2880 if c.key == "arr" else 1440)):
                    continue
            else:
                if v < c.gen_lo - span * 0.1 or v > c.hi + span * 0.2:
                    continue
            if c.nonneg and v < 0:
                continue
            if c.hi_cap is not None and v > c.hi_cap:
                continue
        out.append(v)
    ref = cur if (cur is not None and cur != INF and cur not in c.special) else None
    if ref is not None:
        out.sort(key=lambda v: (abs(v - ref) if (v != INF and v not in c.special) else 10 ** 9) * rng.uniform(0.6, 1.4))
    else:
        rng.shuffle(out)
    return out[:45]


def spec_ents(s):
    return [s[k] for k in ("e", "a", "b") if k in s]


def try_cells(t, op, s, cells, target, evalf, rng, consts):
    base = snap(t)
    for (e, k) in cells:
        if e not in t.v:
            continue
        if k.startswith("_"):
            cand = [not t.v[e].get(k)]
            c = None
        else:
            c = t.col(k)
            if c.virtual or k in t.derived or (t.editable is not None and k not in t.editable):
                continue
            cur = t.corr.get((e, k), t.v[e].get(k))
            cand = cand_values(t, c, e, cur, consts, rng)
        for nv in cand:
            if (e, k) in t.corr:
                if nv == t.v[e][k]:
                    continue
                t.corr[(e, k)] = nv
            else:
                t.v[e][k] = nv
            t.apply_derive()
            if t.is_valid():
                v = evalf(t)
                if v == target:
                    return ("cell", e, k)
            restore(t, base)
    return None


def table_edit(t, op, s, target, evalf, rng, from_n, to_n):
    """Change ONE decisive fact of the table so that evalf(t) == target. Mutates t on success."""
    base = snap(t)
    consts = op.consts(t, s) if hasattr(op, "consts") else []
    cells = list(dict.fromkeys(op.cells(t, s)))
    rng.shuffle(cells)
    if to_n:  # blank a decisive cell, or drop the row the claim is about (partial tables only)
        for (e, k) in cells:
            if k.startswith("_") or e not in t.v:
                continue
            c = t.col(k)
            if not can_blank(t, e, c):
                continue
            t.v[e][k] = None
            if evalf(t) == target:
                return ("blank", e, k)
            restore(t, base)
        if t.partial and op.name in ("val", "thr", "cmp", "catval", "diff"):
            for e in spec_ents(s):
                if e in t.v and len(t.rows) > 4 and not any(x == e for (x, _) in t.corr):
                    t.rows.remove(e)
                    del t.v[e]
                    if evalf(t) == target:
                        return ("remove_row", e, None)
                    restore(t, base)
        return None
    if from_n:  # fill a blank decisive cell, or add the unlisted row the claim is about
        blanks = [(e, k) for (e, k) in cells if e in t.v and not k.startswith("_") and t.v[e].get(k) is None]
        r = try_cells(t, op, s, blanks, target, evalf, rng, consts)
        if r:
            return ("fill", r[1], r[2])
        if getattr(t, "mkrow", None):
            for e in spec_ents(s):
                if e in t.v:
                    continue
                for _ in range(3):
                    row = t.mkrow(rng, e)
                    pos = rng.randint(0, len(t.rows))
                    t.rows.insert(pos, e)
                    t.v[e] = row
                    t.apply_derive()
                    if t.is_valid() and evalf(t) == target:
                        return ("add_row", e, None)
                    cells2 = [(x, k) for (x, k) in dict.fromkeys(op.cells(t, s)) if x == e]
                    r = try_cells(t, op, s, cells2, target, evalf, rng, consts)
                    if r:
                        return ("add_row", e, r[2])
                    restore(t, base)
        return None
    r = try_cells(t, op, s, cells[:14], target, evalf, rng, consts)
    return r


