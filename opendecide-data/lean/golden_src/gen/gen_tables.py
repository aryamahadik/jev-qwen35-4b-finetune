class PickSup:
    name = "pick_sup"

    def sample(self, t, rng):
        cs = [c for c in cols_for(t, "sup")]
        if not cs:
            return None
        c = rng.choice(cs)
        hi = rng.random() < 0.6
        ents = known(t, c)
        k = min(len(ents), rng.choice([3, 4, 4, 5]))
        if k < 3:
            return None
        srt = sorted(ents, key=lambda e: t.get(e, c.key), reverse=hi)
        cands = srt[:2] if rng.random() < 0.7 else []
        rest = [x for x in ents if x not in cands]
        rng.shuffle(rest)
        cands = (cands + rest)[:k]
        rng.shuffle(cands)
        s = {"op": "pick_sup", "col": c.key, "hi": hi, "cands": cands}
        return s if self.answer(t, s) else None

    def answer(self, t, s):
        vals = [(t.get(e, s["col"]), e) for e in s["cands"] if e in t.v]
        if len(vals) != len(s["cands"]) or any(v is None for v, _ in vals):
            return None
        best = max(v for v, _ in vals) if s["hi"] else min(v for v, _ in vals)
        es = [e for v, e in vals if v == best]
        return es[0] if len(es) == 1 else None

    def question(self, t, s):
        return f"Which of these {t.ent.pl} {sup_pred(t.col(s['col']), s['hi'])}?"

    def cells(self, t, s):
        from tab_ops import dep_cells
        return [x for e in s["cands"] for x in dep_cells(t, s["col"], e)]

    def consts(self, t, s):
        return [(s["col"], t.get(e, s["col"])) for e in s["cands"] if t.get(e, s["col"]) not in (None, INF)]

    def edges(self, t, s):
        c = t.col(s["col"])
        out = {"table"} | ({"multi_hop"} if c.virtual else set())
        if c.kind in ("time", "date", "dur"):
            out.add("temporal")
        if c.numeric:
            out.add("numeric")
        return out


class PickFilter(PickSup):
    name = "pick_filter"

    def sample(self, t, rng):
        f = pick_filter(t, rng, minsize=2)
        if not f:
            return None
        cs = cols_for(t, "sup")
        if not cs:
            return None
        c = rng.choice(cs)
        hi = rng.random() < 0.6
        s = {"op": "pick_filter", "col": c.key, "hi": hi, "filt": f, "cands": []}
        mem = members(t, s)
        if len(mem) < 2 or any(t.get(e, c.key) is None for e in mem):
            return None
        ans = self._ans(t, s)
        if ans is None:
            return None
        outside = [e for e in t.rows if e not in mem and t.get(e, c.key) is not None]
        trap = []
        if outside:
            ext = max(outside, key=lambda e: t.get(e, c.key)) if hi else min(outside, key=lambda e: t.get(e, c.key))
            trap = [ext]
        others = [e for e in mem if e != ans] + [e for e in outside if e not in trap]
        rng.shuffle(others)
        k = min(rng.choice([3, 4, 4, 5]), 1 + len(trap) + len(others))
        if k < 3:
            return None
        cands = [ans] + trap + others
        cands = cands[:k]
        rng.shuffle(cands)
        s["cands"] = cands
        return s if self.answer(t, s) == ans else None

    def _ans(self, t, s):
        mem = members(t, s)
        vals = [(t.get(e, s["col"]), e) for e in mem]
        if len(vals) < 2 or any(v is None for v, _ in vals):
            return None
        best = max(v for v, _ in vals) if s["hi"] else min(v for v, _ in vals)
        es = [e for v, e in vals if v == best]
        return es[0] if len(es) == 1 else None

    def answer(self, t, s):
        a = self._ans(t, s)
        return a if a in s["cands"] else None

    def question(self, t, s):
        if t.partial:
            return f"Of the {t.ent.pl} shown, which one{filt_phrase(t, s)} {sup_pred(t.col(s['col']), s['hi'])}?"
        return f"Which {t.ent.sg}{filt_phrase(t, s)} {sup_pred(t.col(s['col']), s['hi'])}?"

    def cells(self, t, s):
        from tab_ops import dep_cells
        return [x for e in members(t, s) for x in dep_cells(t, s["col"], e)]

    def edges(self, t, s):
        return PickSup.edges(self, t, s) | {"multi_hop"}


class PickVal(PickSup):
    name = "pick_val"

    def sample(self, t, rng):
        cs = [c for c in cols_for(t, "val") if not c.unl]
        if not cs:
            return None
        c = rng.choice(cs)
        ents = known(t, c)
        vals = collections.Counter(t.get(e, c.key) for e in ents)
        uniq = [e for e in ents if vals[t.get(e, c.key)] == 1 and is_int(t.get(e, c.key))]
        if not uniq or len(ents) < 3:
            return None
        e = rng.choice(uniq)
        x = t.get(e, c.key)
        others = sorted([o for o in ents if o != e], key=lambda o: abs(t.get(o, c.key) - x))
        k = min(len(ents), rng.choice([3, 4, 4, 5]))
        cands = [e] + others[:k - 1]
        rng.shuffle(cands)
        s = {"op": "pick_val", "col": c.key, "v": int(x), "cands": cands}
        return s if self.answer(t, s) == e else None

    def answer(self, t, s):
        hits = [e for e in t.rows if t.get(e, s["col"]) == s["v"]]
        return hits[0] if len(hits) == 1 and hits[0] in s["cands"] else None

    def question(self, t, s):
        c = t.col(s["col"])
        V = vs(c, s["v"], s)
        sg = t.ent.sg
        if "eq" in c.custom:
            q = c.custom["eq"][0].format(E=f"which {sg}", P=f"which {sg}'s", V=V)
            return cap(q) + "?"
        if c.vp:
            vp = c.vp
            return f"Which {sg} {vp.verb} {V}{objf(c, s['v'])}{vp.suffix}?"
        if c.tvp:
            verb, base, prep, tense = c.tvp
            return f"Which {sg} {verb} {prep} {V}?"
        return f"Which {sg} has {art(c.noun)} {c.noun} of {V}?"

    def cells(self, t, s):
        return []

    def mutate(self, t, s, rng):
        cur = self.answer(t, s)
        opts = []
        for e in s["cands"]:
            if e == cur:
                continue
            x = t.get(e, s["col"])
            if x is None or x == INF or not is_int(x):
                continue
            if sum(t.get(o, s["col"]) == x for o in t.rows) == 1:
                opts.append(int(x))
        return dict(s, v=rng.choice(opts)) if opts else None


