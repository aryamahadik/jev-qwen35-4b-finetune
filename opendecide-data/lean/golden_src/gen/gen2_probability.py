def recheck(row):
    sname, fid, P, qid, ev, thr, bset, extra = row["_chk"]
    S = SCH[sname]
    fr = next(f for f in S.frames if f["id"] == fid)
    st = row["state"]
    assert row["meta"]["orig_label"]["params"] == J(P)
    if sname == "ev":
        order, xy, tie_opt = ev, thr, extra
        v1, v2 = S.values(P, fr), S.values2(P, fr)
        assert v1 == v2, (row["rid"], v1, v2)
        S.check_money(P, fr, st)
        kinds = [k for k, _ in P["opts"]]
        stated = {"bonus": [("p", "gamble"), ("q", "gamble2")], "routes": [("p", "bridge"), ("q", "fog")]}.get(fr["id"], [("p", None)])
        for key, need in stated:
            if need is None or need in kinds:
                assert num_in(st, P[key], "p"), (row["rid"], key)
        if qid == "pick":
            b = S.best(v2, fr["goal"])
            want = "no difference" if b is None else S.LABELS[order.index(b)]
            if b is None:
                assert len(set(v2)) == 1
        else:
            vx, vy = v2[order[xy[0]]], v2[order[xy[1]]]
            want = "yes" if ((vx > vy) if fr["goal"] == "max" else (vx < vy)) else "no"
            assert vx != vy
        assert want == row["gold"], (row["rid"], want, row["gold"])
        for i, lab in enumerate(S.LABELS[:len(order)]):
            assert f"{lab}:" in st
        return
    if sname == "table":
        S._ev = ev
        p1 = S.prob(P, ev, fr)
        p2 = S.prob2(P, ev, fr, state=st)          # counts re-parsed from the rendered table
    elif qid == "pick":
        pa1, pb1 = S.prob(P, ev[0], fr), S.prob(P, ev[1], fr)
        pa2, pb2 = S.prob2(P, ev[0], fr), S.prob2(P, ev[1], fr)
        assert (pa1, pb1) == (pa2, pb2), row["rid"]
        want = pick_gold(pa2, pb2)
        assert want == row["gold"], (row["rid"], want, row["gold"])
        if want != "no difference":
            assert abs(pa2 - pb2) >= max(F(1, 100), max(pa2, pb2) / 20)
        for v, kind in S.check_numbers(P, fr):
            assert num_in(st, v, kind), (row["rid"], v, kind)
        return
    else:
        p1 = S.prob(P, ev, fr)
        p2 = S.prob2(P, ev, fr)
    assert p1 == p2, (row["rid"], p1, p2)
    assert 0 < p2 < 1
    for v, kind in S.check_numbers(P, fr):
        assert num_in(st, v, kind), (row["rid"], v, kind, st)
    if hasattr(S, "extra_checks"):
        S.extra_checks(row, P, fr)
    if qid == "outcome":
        assert outcome_ok(p2)
        assert row["gold"] == ("yes" if p2 > F(1, 2) else "no")
        assert abs(row["soft"]["yes"] - float(p2)) < 1e-6 and abs(row["soft"]["yes"] + row["soft"]["no"] - 1) < 1e-9
    elif qid == "threshold":
        t, mode = thr
        assert abs(p2 - t) >= t_margin(t)
        yes = (p2 > t) if mode in ("gt", "mltn") else (p2 < t)
        assert row["gold"] == ("yes" if yes else "no") and row["soft"] is None
        tt = row["instructions"]
        assert (fmt_t(t, "pct") in tt or fmt_t(t, "one") in tt or mode == "mltn"), (row["rid"], tt)
    else:
        edges, labs = BIN_SETS[bset]
        bi, ok = bin_of(p2, edges)
        assert ok and row["gold"] == labs[bi] and row["soft"] is None


