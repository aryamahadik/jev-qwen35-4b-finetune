def num_in(state, v, kind):
    if kind == "p":
        pats = []
        for s in ("pct", "dec", "one"):
            if ok_style(v, s):
                t = fmt(v, s)
                pats.append(r"(?<![\d.])" + re.escape(t) + ("" if s == "pct" else r"(?![\d%])"))
                if s == "one":
                    pats.append(r"(?<![\d.])" + re.escape(t.replace(" ", "-")) + r"(?![\d%])")
        return any(re.search(x, state) for x in pats)
    if kind == "int":
        return re.search(r"(?<![\d.,$])" + re.escape(f"{v:,}" if v >= 10000 else str(v)) + r"(?![\d])", state) is not None
    if kind == "money":
        return money(v) in state
    raise ValueError(kind)


