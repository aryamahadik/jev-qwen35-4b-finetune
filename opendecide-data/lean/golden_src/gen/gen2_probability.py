def alloc(n, w):
    tot = sum(w.values())
    base = {k: n * v // tot for k, v in w.items()}
    rem = n - sum(base.values())
    for k in sorted(w, key=lambda k: (-(n * w[k] % tot), k))[:rem]:
        base[k] += 1
    return base


