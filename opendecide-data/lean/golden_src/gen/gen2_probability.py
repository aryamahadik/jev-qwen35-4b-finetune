    def outcomes(self, prm, o, fr):
        kind, d = o
        f, p = fr["id"], prm.get("p")
        if f == "bonus":
            if kind == "fixed":
                return [(F(1), d["a"])]
            if kind == "gamble":
                return [(p, d["hi"]), (1 - p, d["lo"])]
            return [(prm["q"], d["hi"]), (1 - prm["q"], d["lo"])]
        if f == "warranty":
            if kind == "buy":
                return [(F(1), d["w"])]
            if kind == "skip":
                return [(p, prm["c"]), (1 - p, 0)]
            return [(p, d["w"] + F(prm["c"], 2)), (1 - p, d["w"])]
        if f == "routes":
            if kind == "fixed":
                return [(F(1), d["t"])]
            pr = p if kind == "bridge" else prm["q"]
            return [(1 - pr, d["t1"]), (pr, d["t2"])]
        if f == "crops":
            return [(1 - p, d["wet"]), (p, d["dry"])]
        if f == "insurance":
            return [(p, d["prem"] + d["ded"]), (1 - p, d["prem"])]
        if f == "guitar":
            if kind == "fixed":
                return [(F(1), d["a"])]
            return [(p, d["hi"]), (1 - p, d["lo"])]
        raise ValueError(f)

    def values(self, prm, fr):
        return [sum((pr * v for pr, v in self.outcomes(prm, o, fr)), F(0)) for o in prm["opts"]]

    def values2(self, prm, fr):
        # independent: expected value = lowest outcome + sum over higher outcomes of P(outcome) * (outcome - lowest)
        out = []
        for o in prm["opts"]:
            oc = self.outcomes(prm, o, fr)
            assert sum(pr for pr, _ in oc) == 1
            base = min(v for _, v in oc)
            out.append(base + sum((pr * (v - base) for pr, v in oc), F(0)))
        return out

    def best(self, vals, goal):
        tgt = max(vals) if goal == "max" else min(vals)
        idx = [i for i, v in enumerate(vals) if v == tgt]
        return idx[0] if len(idx) == 1 else None

