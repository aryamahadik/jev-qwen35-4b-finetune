class Sty:
    """Deterministic surface choices for one pair (base and twin share it, so only the changed fact differs)."""

    def __init__(self, seed):
        self.seed = seed
        self.rec = []         # (formatted text, style); the units tag counts styles that actually appear in the state
        self.flag_edges, self.flag_traps = set(), set()

    def rr(self, tag):
        return random.Random(f"{self.seed}|{tag}")

    def choice(self, tag, seq):
        seq = list(seq)
        return seq[self.rr(tag).randrange(len(seq))]

    def p(self, tag, f, allow=("pct", "one", "dec")):
        av = [s for s in allow if ok_style(f, s)]
        if not av:
            av = [s for s in ("pct", "dec", "one") if ok_style(f, s)]
        w = {"pct": 6, "one": 3, "dec": 2}
        u = self.rr(tag).random() * sum(w[s] for s in av)
        st = av[-1]
        for s in av:
            u -= w[s]
            if u < 0:
                st = s
                break
        self.rec.append((fmt(f, st), st))
        return fmt(f, st)

    def ch(self, tag, f, allow=("pct", "one", "dec")):
        s = self.p(tag, f, allow)
        st = self.rec[-1][1]
        if st == "one":
            out = f"a {s.replace(' ', '-')} chance"
        elif st == "dec":
            out = f"a probability of {s}"
        else:
            out = f"{art(s)} {s} chance"
        self.rec[-1] = (out, st)
        return out

    def pct(self, tag, f):
        return self.p(tag, f, ("pct",))

    def vals(self):
        nm = self.choice("name", NAMES)
        return {"name": nm, "co": self.choice("co", COS), "town": self.choice("town", TOWNS),
                "island": self.choice("island", ISLANDS), "team": self.choice("team", TEAMS)}


