class Ctx:
    def __init__(self):
        self.frame_use = collections.Counter()
        self.frame_fail = collections.Counter()
        self.gold_use = collections.Counter()


def least(ctx, key, opts, rng):
    m = min(ctx.gold_use[(key, o)] for o in opts)
    c = [o for o in opts if ctx.gold_use[(key, o)] == m]
    return rng.choice(c)


def choose_frame(ctx, S, qid, rng):
    frs = [fr for fr in S.frames if qid != "pick" or S.name == "ev" or S.cmp_pairs]
    score = lambda fr: ctx.frame_use[(S.name, qid, fr["id"])] + 4 * ctx.frame_fail[(S.name, qid, fr["id"])]
    m = min(score(fr) for fr in frs)
    fr = rng.choice([fr for fr in frs if score(fr) == m])
    ctx.last_frame = (S.name, qid, fr["id"])
    return fr


def seg_diff(a, b):
    sa = re.split(r"(?<=[.;:?])\s+|\n", a)
    sb = re.split(r"(?<=[.;:?])\s+|\n", b)
    ca, cb = collections.Counter(sa), collections.Counter(sb)
    return sum(((ca - cb) + (cb - ca)).values())


def outcome_ok(p):
    return F(3, 1000) <= p <= F(997, 1000) and abs(p - F(1, 2)) >= F(4, 100)


