class Net(Schema):
    """Components that must all work (series) or of which one is enough (parallel)."""

    def __init__(self, name, frames, mode):
        self.name, self.frames, self.mode = name, frames, mode

    def sample(self, rng, fr, tie=False):
        m = rng.randint(fr["m"][0], min(fr["m"][1], len(fr["comps"])))
        idx = sorted(rng.sample(range(len(fr["comps"])), m))
        return {"idx": idx, "x": [rng.choice(fr["pool"]) for _ in idx]}

    def muts(self, prm, fr):
        out = []
        for i in range(len(prm["idx"])):
            for v in fr["pool"]:
                if v != prm["x"][i]:
                    x = list(prm["x"])
                    x[i] = v
                    out.append((f"x{i}", dict(prm, x=x)))
            if len(prm["idx"]) > fr["m"][0]:
                out.append((f"drop{i}", {"idx": prm["idx"][:i] + prm["idx"][i + 1:], "x": prm["x"][:i] + prm["x"][i + 1:]}))
        return out

    def ps(self, prm, fr):
        return [1 - x if fr["pol"] == "fail" else x for x in prm["x"]]

    def tree(self, prm):
        leaves = [("leaf", i) for i in range(len(prm["x"]))]
        return ("all", leaves) if self.mode == "series" else ("any", leaves)

    def prob(self, prm, ev, fr):
        p = net_p1(self.tree(prm), self.ps(prm, fr))
        return p if ev == "works" else 1 - p

    def prob2(self, prm, ev, fr):
        p = net_p2(self.tree(prm), self.ps(prm, fr))
        return p if ev == "works" else 1 - p

    def render(self, prm, fr, sty, V):
        sents = [fr["intro"].format(**V)]
        for j, (i, x) in enumerate(zip(prm["idx"], prm["x"])):
            sents.append(fr["comps"][i].format(x=sty.p(f"x{i}", x), **V))
        sents.append(fr["indep"])
        return compose(sty, fr["head"], fr["role"], sents, [])

    def check_numbers(self, prm, fr):
        return [(x, "p") for x in prm["x"]]

    def traps(self, prm, ev, fr):
        return ["complement_rule"] if fr["pol"] == "fail" else []


