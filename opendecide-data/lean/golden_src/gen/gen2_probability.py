# ============================================================================================ exact probability
def cmp_ok(j, op, k):
    return {"ge": j >= k, "gt": j > k, "le": j <= k, "lt": j < k, "eq": j == k}[op]


def binom_p1(n, r, op, k):
    if op == "ge" and k == 1:
        return 1 - (1 - r) ** n
    if op == "eq" and k == 0:
        return (1 - r) ** n
    return sum((comb(n, j) * r ** j * (1 - r) ** (n - j) for j in range(n + 1) if cmp_ok(j, op, k)), F(0))


def binom_p2(n, r, op, k):
    dist = [F(1)]
    for _ in range(n):
        nd = [F(0)] * (len(dist) + 1)
        for j, q in enumerate(dist):
            nd[j] += q * (1 - r)
            nd[j + 1] += q * r
        dist = nd
    return sum((q for j, q in enumerate(dist) if cmp_ok(j, op, k)), F(0))


def hyper_p1(N, K, n, op, k):
    return sum((F(comb(K, j) * comb(N - K, n - j), comb(N, n)) for j in range(min(K, n) + 1) if cmp_ok(j, op, k)), F(0))


def hyper_p2(N, K, n, op, k):
    dist = {0: F(1)}
    for t in range(n):
        nd = collections.defaultdict(F)
        for b, q in dist.items():
            left, bad = N - t, K - b
            if bad:
                nd[b + 1] += q * F(bad, left)
            if left - bad:
                nd[b] += q * F(left - bad, left)
        dist = nd
    return sum((q for b, q in dist.items() if cmp_ok(b, op, k)), F(0))


def net_p1(node, ps):
    t = node[0]
    if t == "leaf":
        return ps[node[1]]
    if t == "all":
        return prod((net_p1(c, ps) for c in node[1]), start=F(1))
    if t == "any":
        return 1 - prod((1 - net_p1(c, ps) for c in node[1]), start=F(1))
    if t == "kofn":
        dist = [F(1)]
        for c in node[2]:
            q = net_p1(c, ps)
            nd = [F(0)] * (len(dist) + 1)
            for j, x in enumerate(dist):
                nd[j] += x * (1 - q)
                nd[j + 1] += x * q
            dist = nd
        return sum(dist[node[1]:], F(0))
    raise ValueError(t)


def net_eval(node, up):
    t = node[0]
    if t == "leaf":
        return up[node[1]]
    if t == "all":
        return all(net_eval(c, up) for c in node[1])
    if t == "any":
        return any(net_eval(c, up) for c in node[1])
    return sum(net_eval(c, up) for c in node[2]) >= node[1]


def net_p2(node, ps):
    tot = F(0)
    for up in itertools.product([True, False], repeat=len(ps)):
        w = prod((ps[i] if u else 1 - ps[i] for i, u in enumerate(up)), start=F(1))
        if net_eval(node, up):
            tot += w
    return tot


def bern_enum(ps):
    for up in itertools.product([True, False], repeat=len(ps)):
        yield up, prod((ps[i] if u else 1 - ps[i] for i, u in enumerate(up)), start=F(1))


