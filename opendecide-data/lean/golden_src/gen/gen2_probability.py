# ============================================================================================ number formatting
def _dec(f, maxdp):
    for dp in range(maxdp + 1):
        v = f * 10 ** dp
        if v.denominator == 1:
            s = str(abs(v.numerator)).rjust(dp + 1, "0")
            return s if dp == 0 else s[:-dp] + "." + s[-dp:]
    return None


def ok_style(f, st):
    if st == "pct":
        return _dec(f * 100, 2) is not None
    if st == "dec":
        return _dec(f, 4) is not None
    if st == "one":
        return f.numerator == 1 and 2 < f.denominator <= 10000
    raise ValueError(st)


def fmt(f, st):
    assert 0 <= f <= 1 and ok_style(f, st), (f, st)
    if st == "pct":
        return _dec(f * 100, 2) + "%"
    if st == "dec":
        return _dec(f, 4)
    return f"1 in {f.denominator:,}"


def art(s):
    return "an" if s[0] == "8" or re.match(r"(11|18)(\D|$)", s) else "a"


def money(v):
    assert v == int(v)
    return f"${int(v):,}"


def J(x):
    if isinstance(x, F):
        return str(x.numerator) if x.denominator == 1 else f"{x.numerator}/{x.denominator}"
    if isinstance(x, dict):
        return {k: J(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [J(v) for v in x]
    return x


def cap(s):
    return s[:1].upper() + s[1:]


